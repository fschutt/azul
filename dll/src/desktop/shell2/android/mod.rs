/// Events generated by the Android backend (currently only the close signal).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AndroidEvent {
    Close,
}

/// Rendering backend selector. CPU only on day 1 (mirrors the headless backend).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RenderBackend {
    Cpu,
}

/// Android platform window backed by an `ANativeWindow`.
///
/// The window pointer is `None` while the activity is in the background
/// (`MainEvent::TerminateWindow` fires before `Pause`). All rendering and hit
/// testing must be guarded against that case.
pub struct AndroidWindow {
    /// Cross-platform window state (layout, resources, event diffing).
    pub common: CommonWindowState,
    /// CPU rendering backend (replaces WebRender).
    pub cpu_backend: CpuBackend,
    /// Currently-attached `ANativeWindow`. Released on `TerminateWindow`.
    #[cfg(feature = "ndk")]
    pub native_window: Option<NativeWindow>,
    /// Rendering backend selector (always Cpu for now).
    pub backend: RenderBackend,
    /// `false` once `MainEvent::Destroy` arrives; breaks the outer loop.
    pub is_open: bool,
    /// Theme change queued by the Java-UI-thread JNI hook
    /// (`nativeOnUiModeChanged`), drained on the LOOP thread each iteration.
    /// Encoding matches the JNI contract: 0 = none pending, 1 = light,
    /// 2 = dark. The Java thread must never mutate window state or run a
    /// pass itself — that is what left a live delta for the validation check
    /// and raced the loop's own reads.
    pub pending_theme: std::sync::atomic::AtomicI32,
    /// Shared icon provider — needed by `regenerate_layout()` so widgets
    /// (notably button/icon containers) can resolve `IconReference`s.
    pub icon_provider: SharedIconProvider,
    /// Shared font registry for async font discovery / loading.
    /// `None` means the registry was never installed; defaults to disabled.
    pub font_registry: Option<Arc<FcFontRegistry>>,
    /// `AccessibilityNodeProvider` bridge: the virtual-view tree TalkBack
    /// reads and the queue the actions it performs land in. Hand-written
    /// because `accesskit` has no Android adapter.
    ///
    /// Read from the Java UI thread via JNI while the loop thread writes it,
    /// which is why its state is behind a lock and why nothing in it touches
    /// the `LayoutWindow`.
    pub accessibility_adapter: accessibility::AndroidAccessibilityAdapter,
}

impl AndroidWindow {
    /// Construct a window with no native surface attached yet.
    /// `InitWindow` later swaps in the real `ANativeWindow`.
    pub fn new(
        options: WindowCreateOptions,
        fc_cache: Arc<FcFontCache>,
        mut config: AppConfig,
        app_data: RefAny,
        undo_manager: event::SharedUndoManager,
        font_registry: Option<Arc<FcFontRegistry>>,
    ) -> Result<Self, WindowError> {
        // `WindowCreateOptions::window_state` is already a `FullWindowState`,
        // mirroring how `HeadlessWindow::new` consumes it. No constructor call.
        let full_window_state = options.window_state;

        // Extract the SharedIconProvider out of the config (same pattern
        // as run_headless) so we can pass it to regenerate_layout later.
        let icon_provider_handle = core::mem::take(&mut config.icon_provider);
        let icon_provider = SharedIconProvider::from_handle(icon_provider_handle);

        let mut layout_window = LayoutWindow::new(fc_cache.as_ref().clone())
            .map_err(|e| WindowError::PlatformError(format!("Layout init failed: {:?}", e)))?;
        layout_window.current_window_state = full_window_state.clone();
        layout_window.routes = config.routes.clone();

        let mut common = CommonWindowState::new(
            full_window_state,
            fc_cache,
            Arc::new(azul_css::system::SystemStyle::default()),
            Arc::new(RefCell::new(app_data)),
            undo_manager,
        );
        common.layout_window = Some(layout_window);
        common.cpu_hit_tester = Some(azul_layout::headless::CpuHitTester::new());

        Ok(Self {
            common,
            cpu_backend: CpuBackend::new(),
            #[cfg(feature = "ndk")]
            native_window: None,
            backend: RenderBackend::Cpu,
            is_open: true,
            pending_theme: std::sync::atomic::AtomicI32::new(0),
            icon_provider,
            font_registry,
            accessibility_adapter: accessibility::AndroidAccessibilityAdapter::new(),
        })
    }

    pub fn is_open(&self) -> bool {
        self.is_open
    }

    /// Drain the accessibility actions TalkBack queued and apply them.
    ///
    /// Mirrors `Win32Window::process_accessibility_actions` /
    /// `X11Window::process_accessibility_actions`: poll the adapter, route each
    /// action through `LayoutWindow::process_accessibility_action`, dispatch the
    /// callbacks it maps to, honour the `Update` they return. Android had NO
    /// such method, so even once the provider existed a `performAction` would
    /// have had nowhere to go.
    ///
    /// Runs on the loop thread, never in the JNI upcall: `performAction`
    /// arrives on the Java UI thread, and mutating the `LayoutWindow` from
    /// there would race the frame loop.
    #[cfg(feature = "a11y")]
    pub fn process_accessibility_actions(&mut self) {
        let mut actions = Vec::new();
        while let Some(action) = self.accessibility_adapter.poll_action() {
            actions.push(action);
        }
        if actions.is_empty() {
            return;
        }
        self.dispatch_accessibility_actions(actions);
        // Unconditional, like every desktop backend's `request_redraw()`:
        // Focus / Blur / the Scroll* family map to no callback and return an
        // empty affected set while having genuinely changed the screen.
        self.common
            .request_regeneration(azul_core::callbacks::RelayoutReason::RefreshDom);
    }

    /// Rebuild the virtual-view tree the Java provider reads.
    ///
    /// Android's equivalent of the desktop backends' `adapter.update_tree()`.
    /// The Java side is additionally told to invalidate, so TalkBack re-reads
    /// instead of highlighting where things used to be.
    #[cfg(feature = "a11y")]
    fn refresh_accessibility_tree(&mut self) {
        let Some(lw) = self.common.layout_window.as_ref() else {
            return;
        };
        let snapshot = lw.build_a11y_snapshot();
        // Android wants physical pixels. `android_main` derives the framework
        // dpi as `density * 96 / 160`, so the android scale (`density / 160`)
        // is exactly `dpi / 96` — the same factor everything else here uses.
        let scale = self.common.current_window_state().size.dpi as f32 / 96.0;
        self.accessibility_adapter.update_snapshot(snapshot, scale);
        self.common.a11y_dirty = false;
    }
    pub fn close(&mut self) {
        // See CommonWindowState::deinit_renderer — webrender requires it.
        self.common.deinit_renderer();
        self.is_open = false;
    }

    /// Run a full layout regeneration pass and CPU-render the resulting
    /// display list. Mirrors `HeadlessWindow::regenerate_layout()`; the
    /// lifecycle-event dispatch step is skipped for now (Android backend
    /// has no callback driver yet — pending sprint H).
    pub fn regenerate_layout_inner(
        &mut self,
    ) -> Result<crate::desktop::shell2::common::layout::LayoutRegenerateResult, String> {
        // Captured BEFORE the pass: `regenerate_layout` (the trait wrapper that
        // calls this) drains lifecycle callbacks between passes, and one of
        // those returning `Update::RefreshDom` raises a NEW request. Retiring
        // by epoch at the end means this pass only retires the request it
        // actually saw.
        let regen_epoch_seen = self.common.regen_epoch();

        // Consume the reason tag BEFORE borrowing the layout window: this is
        // the regeneration this window asked for, and the tag travels with
        // the request (see CommonWindowState::request_regeneration).
        let relayout_reason = self.common.take_relayout_reason();

        let borrows = self.common.layout_borrows();
        let layout_window = borrows.layout_window.ok_or("No layout window")?;

        let debug_enabled = crate::desktop::shell2::common::debug_server::is_debug_enabled();
        let mut debug_messages = if debug_enabled {
            Some(Vec::new())
        } else {
            None
        };

        let result = crate::desktop::shell2::common::layout::regenerate_layout(
            layout_window,
            borrows.app_data,
            borrows.current_window_state,
            borrows.renderer_resources,
            borrows.gl_context_ptr,
            borrows.fc_cache,
            &self.font_registry,
            borrows.system_style,
            &self.icon_provider,
            &mut debug_messages,
            relayout_reason,
        )?;

        if let Some(msgs) = debug_messages {
            for msg in msgs {
                crate::desktop::shell2::common::debug_server::log(
                    crate::desktop::shell2::common::debug_server::LogLevel::Debug,
                    crate::desktop::shell2::common::debug_server::LogCategory::Layout,
                    msg.message.as_str().to_string(),
                    None,
                );
            }
        }

        // Rebuild CPU hit-tester from new layout results
        if let Some(lw) = self.common.layout_window.as_ref() {
            self.cpu_backend
                .hit_tester
                .rebuild_from_layout_with_gpu(&lw.layout_results, Some(&lw.gpu_state_manager));
        }

        // Drain lifecycle events (Mount / AfterMount / Unmount) produced by this
        // layout's reconciliation — the SAME step headless + X11 run. Without it,
        // EventFilter::Component(AfterMount) callbacks never fire on Android (e.g.
        // the MapWidget's first tile fetch never starts).

        // #27 native backbuffer: Android stays LEGACY by design.
        // `ANativeWindow_lock` rotates double/triple buffers with NO content
        // guarantee and no way to preserve a buffer's pixels across cycles
        // (NDK-documented), so the renderer's incremental base would be
        // garbage. Going native needs the Wayland slot model keyed by the
        // returned bits pointer (per-buffer stale tracking + the in/out
        // dirty-bounds contract); design when a device run exists to verify.
        //
        // CPU-render the frame — populates `self.cpu_backend.last_frame`
        // so the next `render_frame()` call can blit pixels.
        #[cfg(feature = "cpurender")]
        {
            let ws = self.common.current_window_state();
            let width = ws.size.dimensions.width;
            let height = ws.size.dimensions.height;
            let dpi = ws.size.dpi as f32 / 96.0;
            // Shared per-frame content preparation (journal clock, image
            // callbacks through the content chokepoint, scrollbar cache).
            // Before this, image callbacks were NEVER invoked on this host —
            // every callback image rendered as the announced grey placeholder.
            if let Some(lw) = self.common.layout_window.as_mut() {
                lw.prepare_frame_cpu();
            }
            if let Some(lw) = self.common.layout_window.as_ref() {
                self.cpu_backend.render_frame(
                    lw,
                    &self.common.renderer_resources,
                    width,
                    height,
                    dpi,
                );
            }
        }

        // Republish the virtual-view tree. Bounds, labels and the focused node
        // all just changed and TalkBack reads a cached tree, so without this it
        // keeps announcing (and highlighting) the previous layout.
        #[cfg(feature = "a11y")]
        self.refresh_accessibility_tree();

        self.common
            .clear_regeneration_unless_reraised(regen_epoch_seen);
        Ok(result)
    }
}

impl PlatformWindow for AndroidWindow {
    fn regenerate_layout_once(
        &mut self,
    ) -> Result<crate::desktop::shell2::common::layout::LayoutRegenerateResult, String> {
        // The single pass. The bounded lifecycle loop lives in the trait
        // default `regenerate_layout`, which is what frame paths call.
        self.regenerate_layout_inner()
    }

    impl_platform_window_getters!(common);

    fn get_raw_window_handle(&self) -> RawWindowHandle {
        #[cfg(feature = "ndk")]
        let ptr = self
            .native_window
            .as_ref()
            .map(|nw| nw.ptr().as_ptr() as *mut c_void)
            .unwrap_or(std::ptr::null_mut());
        #[cfg(not(feature = "ndk"))]
        let ptr = std::ptr::null_mut();

        RawWindowHandle::Android(AndroidHandle {
            a_native_window: ptr,
        })
    }

    fn prepare_callback_invocation(&mut self) -> event::InvokeSingleCallbackBorrows<'_> {
        let borrows = self.common.layout_borrows();
        event::InvokeSingleCallbackBorrows {
            layout_window: borrows
                .layout_window
                .expect("Layout window must exist for callback invocation"),
            window_handle: RawWindowHandle::Android(AndroidHandle {
                a_native_window: std::ptr::null_mut(),
            }),
            gl_context_ptr: borrows.gl_context_ptr,
            fc_cache_clone: (**borrows.fc_cache).clone(),
            system_style: borrows.system_style.clone(),
            previous_window_state: borrows.previous_window_state,
            current_window_state: borrows.current_window_state,
            renderer_resources: borrows.renderer_resources,
        }
    }

    fn start_timer(&mut self, timer_id: usize, timer: azul_layout::timer::Timer) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            lw.timers
                .insert(azul_core::task::TimerId { id: timer_id }, timer);
        }
    }
    fn stop_timer(&mut self, timer_id: usize) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            lw.timers.remove(&azul_core::task::TimerId { id: timer_id });
        }
    }
    fn start_thread_poll_timer(&mut self) {}
    fn stop_thread_poll_timer(&mut self) {}

    fn add_threads(
        &mut self,
        threads: std::collections::BTreeMap<azul_core::task::ThreadId, azul_layout::thread::Thread>,
    ) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            for (id, thread) in threads {
                lw.threads.insert(id, thread);
            }
        }
    }
    fn remove_threads(
        &mut self,
        thread_ids: &std::collections::BTreeSet<azul_core::task::ThreadId>,
    ) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            for id in thread_ids {
                lw.threads.remove(id);
            }
        }
    }

    fn queue_window_create(&mut self, _options: WindowCreateOptions) {
        // No popup windows on Android; ignored. Sub-activities are a future
        // enhancement and would require launching new Intents from Java.
    }

    fn show_menu_from_callback(
        &mut self,
        _menu: &azul_core::menu::Menu,
        _position: azul_core::geom::LogicalPosition,
        _anchor: Option<azul_core::geom::LogicalRect>,
    ) {
    }

    fn show_tooltip_from_callback(
        &mut self,
        _text: &str,
        _position: azul_core::geom::LogicalPosition,
    ) {
    }

    fn hide_tooltip_from_callback(&mut self) {}

    /// The activity owns the window geometry outright, so there is nothing to
    /// push and no OS-sync baseline to diff (`os_synced_state` stays `None`).
    fn sync_window_state(&mut self) {}
}

