/// Android platform window backed by an `ANativeWindow`.
///
/// The window pointer is `None` while the activity is in the background
/// (`MainEvent::TerminateWindow` fires before `Pause`). All rendering and hit
/// testing must be guarded against that case.
pub struct AndroidWindow {
    /// Cross-platform window state (layout, resources, event diffing).
    pub common: CommonWindowState,
    /// CPU rendering backend (replaces WebRender).
    pub cpu_backend: CpuBackend,
    /// Currently-attached `ANativeWindow`. Released on `TerminateWindow`.
    #[cfg(feature = "ndk")]
    pub native_window: Option<NativeWindow>,
    /// Rendering backend selector (always Cpu for now).
    pub backend: RenderBackend,
    /// `false` once `MainEvent::Destroy` arrives; breaks the outer loop.
    pub is_open: bool,
    /// Theme change queued by the Java-UI-thread JNI hook
    /// (`nativeOnUiModeChanged`), drained on the LOOP thread each iteration.
    /// Encoding matches the JNI contract: 0 = none pending, 1 = light,
    /// 2 = dark. The Java thread must never mutate window state or run a
    /// pass itself — that is what left a live delta for the validation check
    /// and raced the loop's own reads.
    pub pending_theme: std::sync::atomic::AtomicI32,
    /// Shared icon provider — needed by `regenerate_layout()` so widgets
    /// (notably button/icon containers) can resolve `IconReference`s.
    pub icon_provider: SharedIconProvider,
    /// Shared font registry for async font discovery / loading.
    /// `None` means the registry was never installed; defaults to disabled.
    pub font_registry: Option<Arc<FcFontRegistry>>,
    /// `AccessibilityNodeProvider` bridge: the virtual-view tree TalkBack
    /// reads and the queue the actions it performs land in. Hand-written
    /// because `accesskit` has no Android adapter.
    ///
    /// Read from the Java UI thread via JNI while the loop thread writes it,
    /// which is why its state is behind a lock and why nothing in it touches
    /// the `LayoutWindow`.
    pub accessibility_adapter: accessibility::AndroidAccessibilityAdapter,

    /// Monotonic frame counter, bumped once per POSTED frame.
    ///
    /// The unit of the staleness bookkeeping below: a buffer is identified by
    /// its mapped address and tagged with the frame it last received.
    frame_seq: u64,

    /// Which frame each `ANativeWindow` buffer currently holds, keyed by the
    /// address `lock()` mapped it at.
    ///
    /// This is the whole reason partial present is possible here at all.
    /// `ANativeWindow_lock` hands back a DEQUEUED buffer with undefined
    /// contents — Android guarantees nothing about back-buffer preservation —
    /// so "copy only the damage" is unsound in general. It IS sound for a
    /// buffer we can prove still holds a frame we produced: the pool is small
    /// (double/triple buffering) and rotates, so the same addresses come back
    /// round and each one is a known-good base to patch. An address we have
    /// never seen, or one whose frame has aged out of `damage_history`, takes
    /// the full copy.
    buffer_frames: std::collections::BTreeMap<usize, u64>,

    /// Dirty ROW RANGES per recent frame, oldest first: `(frame_seq, rows)`.
    ///
    /// Rows, not rects, because the blit is row-based — a partial row saves no
    /// memcpy, and row granularity already captures what actually changes
    /// (a scrolled region, a caret, a repainted ribbon band).
    damage_history: std::collections::VecDeque<(u64, Vec<(usize, usize)>)>,

    /// Selection-toolbar actions (cut/copy/paste/select-all) from the UI thread.
    pending_selection_actions: std::sync::Mutex<Vec<i32>>,
    /// Whether the floating selection toolbar is up (U2), so it is started and
    /// stopped on the TRANSITION rather than asked for every frame.
    selection_toolbar_shown: bool,

    /// IME text committed on the Java UI thread, waiting for the loop thread.
    ///
    /// `record_text_input` only STAGES a changeset; the shared event pass is
    /// what applies it (`ApplyPendingTextInput` -> `ApplyTextChangeset`), and a
    /// pass must not run from the IME's thread while the loop may be mid-layout.
    /// Same shape as the a11y action queue and the theme queue above.
    pending_ime_commits: std::sync::Mutex<Vec<String>>,

    /// A frame must be re-rastered and posted, but the layout is UNCHANGED.
    ///
    /// Android's `request_redraw()` equivalent, which it did not have: the only
    /// route to a presented frame was `regeneration_pending()`, so every input
    /// that changed a pixel had to claim it had changed the DOM.
    needs_rerender: bool,

    /// Last touch position of an in-progress one-finger pan, in logical px.
    ///
    /// Android delivers absolute positions; the scroll funnel wants deltas, so
    /// the previous sample has to be kept somewhere. `None` between gestures.
    touch_pan_last: Option<azul_core::geom::LogicalPosition>,
}

impl AndroidWindow {
    /// Construct a window with no native surface attached yet.
    /// `InitWindow` later swaps in the real `ANativeWindow`.
    pub fn new(
        options: WindowCreateOptions,
        fc_cache: Arc<FcFontCache>,
        mut config: AppConfig,
        app_data: RefAny,
        undo_manager: event::SharedUndoManager,
        font_registry: Option<Arc<FcFontRegistry>>,
    ) -> Result<Self, WindowError> {
        // `WindowCreateOptions::window_state` is already a `FullWindowState`,
        // mirroring how `HeadlessWindow::new` consumes it. No constructor call.
        let full_window_state = options.window_state;

        // Extract the SharedIconProvider out of the config (same pattern
        // as run_headless) so we can pass it to regenerate_layout later.
        let icon_provider_handle = core::mem::take(&mut config.icon_provider);
        let icon_provider = SharedIconProvider::from_handle(icon_provider_handle);

        let mut layout_window = LayoutWindow::new(fc_cache.as_ref().clone())
            .map_err(|e| WindowError::PlatformError(format!("Layout init failed: {:?}", e)))?;
        layout_window.current_window_state = full_window_state.clone();
        layout_window.routes = config.routes.clone();
        // THE ENGINE DRAWS THE SELECTION HANDLES HERE (U2-a). Android has no
        // handle API for a custom view: `TextView`'s `Editor` draws the
        // teardrops for itself and for nobody else, and `NativeTextBridge`
        // has said so since U2. So the engine paints them and drags them, and
        // this window says so before its first frame.
        layout_window.text_edit_manager.selection_handles = true;

        let mut common = CommonWindowState::new(
            full_window_state,
            fc_cache,
            // The style AppConfig detected at startup, not `SystemStyle::default()`.
            // `default()` carries `Platform::Unknown`, which
            // `OsCondition::from_system_platform` maps to `Any` — and `Any`
            // matches no `@os(...)` arm at all, so EVERY OS-conditional UA rule
            // silently took the fallback branch: classic always-visible
            // scrollbars instead of overlay, `scrollbar-width: auto` instead of
            // thin, the wrong fade timings, and the Material palette replaced by
            // generic defaults. AppConfig's doc comment already promised this is
            // "passed to all windows"; the desktop backends did, mobile did not.
            Arc::new(config.system_style.clone()),
            Arc::new(RefCell::new(app_data)),
            undo_manager,
        );
        common.layout_window = Some(layout_window);
        common.cpu_hit_tester = Some(azul_layout::headless::CpuHitTester::new());

        Ok(Self {
            common,
            cpu_backend: CpuBackend::new(),
            #[cfg(feature = "ndk")]
            native_window: None,
            backend: RenderBackend::Cpu,
            is_open: true,
            pending_theme: std::sync::atomic::AtomicI32::new(0),
            icon_provider,
            font_registry,
            accessibility_adapter: accessibility::AndroidAccessibilityAdapter::new(),
            frame_seq: 0,
            buffer_frames: std::collections::BTreeMap::new(),
            damage_history: std::collections::VecDeque::new(),
            pending_ime_commits: std::sync::Mutex::new(Vec::new()),
            pending_selection_actions: std::sync::Mutex::new(Vec::new()),
            selection_toolbar_shown: false,
            needs_rerender: false,
            touch_pan_last: None,
        })
    }

    pub fn is_open(&self) -> bool {
        self.is_open
    }

    /// Drain the accessibility actions TalkBack queued and apply them.
    ///
    /// Mirrors `Win32Window::process_accessibility_actions` /
    /// `X11Window::process_accessibility_actions`: poll the adapter, route each
    /// action through `LayoutWindow::process_accessibility_action`, dispatch the
    /// callbacks it maps to, honour the `Update` they return. Android had NO
    /// such method, so even once the provider existed a `performAction` would
    /// have had nowhere to go.
    ///
    /// Runs on the loop thread, never in the JNI upcall: `performAction`
    /// arrives on the Java UI thread, and mutating the `LayoutWindow` from
    /// there would race the frame loop.
    #[cfg(feature = "a11y")]
    pub fn process_accessibility_actions(&mut self) {
        let mut actions = Vec::new();
        while let Some(action) = self.accessibility_adapter.poll_action() {
            actions.push(action);
        }
        if actions.is_empty() {
            return;
        }
        self.dispatch_accessibility_actions(actions);
        // Unconditional, like every desktop backend's `request_redraw()`:
        // Focus / Blur / the Scroll* family map to no callback and return an
        // empty affected set while having genuinely changed the screen.
        self.common
            .request_regeneration(azul_core::callbacks::RelayoutReason::RefreshDom);
    }

    /// Rebuild the virtual-view tree the Java provider reads.
    ///
    /// Android's equivalent of the desktop backends' `adapter.update_tree()`.
    /// The Java side is additionally told to invalidate, so TalkBack re-reads
    /// instead of highlighting where things used to be.
    #[cfg(feature = "a11y")]
    fn refresh_accessibility_tree(&mut self) {
        let Some(lw) = self.common.layout_window.as_ref() else {
            return;
        };
        let snapshot = lw.build_a11y_snapshot();
        // Android wants physical pixels. `android_main` derives the framework
        // dpi as `density * 96 / 160`, so the android scale (`density / 160`)
        // is exactly `dpi / 96` — the same factor everything else here uses.
        let scale = self.common.current_window_state().size.dpi as f32 / 96.0;
        self.accessibility_adapter.update_snapshot(snapshot, scale);
        self.common.a11y_dirty = false;
    }
    pub fn close(&mut self) {
        // See CommonWindowState::deinit_renderer — webrender requires it.
        self.common.deinit_renderer();
        self.is_open = false;
    }

    /// Run a full layout regeneration pass and CPU-render the resulting
    /// display list. Mirrors `HeadlessWindow::regenerate_layout()`; the
    /// lifecycle-event dispatch step is skipped for now (Android backend
    /// has no callback driver yet — pending sprint H).
    /// How many frames of damage to remember.
    ///
    /// A buffer comes back round after as many swaps as the pool is deep
    /// (2-3), so a handful covers every realistic rotation. Anything older
    /// falls back to a full copy, which is always correct.
    const DAMAGE_HISTORY: usize = 8;

    /// Dirty row range of a frame's present damage, or `None` for "everything".
    ///
    /// Logical rects -> physical rows: the pixmap is in device pixels and
    /// `FrameDamage` is in logical ones. Rounded OUTWARDS (floor the top, ceil
    /// the bottom) — a row half-covered by damage is a row that changed, and
    /// rounding it away leaves a stale line on screen.
    fn damage_rows(&self, dpi: f32, height: usize) -> Option<Vec<(usize, usize)>> {
        use azul_layout::window::FrameDamage;
        match &self.cpu_backend.last_present_damage {
            FrameDamage::Full => None,
            FrameDamage::None => Some(Vec::new()),
            FrameDamage::Rects(rects) => {
                let mut rows: Vec<(usize, usize)> = rects
                    .iter()
                    .filter_map(|r| {
                        let top = (r.origin.y * dpi).floor().max(0.0) as usize;
                        let bottom = (((r.origin.y + r.size.height) * dpi).ceil().max(0.0)
                            as usize)
                            .min(height);
                        (bottom > top).then_some((top, bottom))
                    })
                    .collect();
                // Merge overlaps so the copy loop never writes a row twice.
                rows.sort_unstable();
                let mut merged: Vec<(usize, usize)> = Vec::with_capacity(rows.len());
                for (top, bottom) in rows {
                    match merged.last_mut() {
                        Some(last) if top <= last.1 => last.1 = last.1.max(bottom),
                        _ => merged.push((top, bottom)),
                    }
                }
                Some(merged)
            }
        }
    }

    /// Rows that changed since frame `seq`, or `None` if that frame has aged
    /// out of the history (in which case only a full copy is sound).
    fn rows_dirty_since(&self, seq: u64) -> Option<Vec<(usize, usize)>> {
        // The oldest entry we still have must be at or before the frame the
        // buffer holds, or there is a gap we cannot account for.
        let oldest = self.damage_history.front().map(|(s, _)| *s)?;
        if seq + 1 < oldest {
            return None;
        }
        let mut rows: Vec<(usize, usize)> = Vec::new();
        for (s, r) in &self.damage_history {
            if *s > seq {
                rows.extend_from_slice(r);
            }
        }
        rows.sort_unstable();
        let mut merged: Vec<(usize, usize)> = Vec::with_capacity(rows.len());
        for (top, bottom) in rows {
            match merged.last_mut() {
                Some(last) if top <= last.1 => last.1 = last.1.max(bottom),
                _ => merged.push((top, bottom)),
            }
        }
        Some(merged)
    }

    /// Re-raster the frame from the CURRENT layout — no layout callback, no
    /// solve, no DOM work.
    ///
    /// This is what a scroll needs. It reads the live scroll offsets out of the
    /// `LayoutWindow` and repaints, which is the whole of the work desktop does
    /// for `ShouldReRenderCurrentWindow` / `ShouldUpdateDisplayListCurrentWindow`.
    /// Android had no such entry point, so those results were escalated to
    /// `RefreshDom` and re-ran the app's `layout()` — measured at 121-443 ms per
    /// frame during a drag on AzWriter, against 6 ms for the same frame when the
    /// callback is skipped.
    pub fn rerender_cpu(&mut self) {
        #[cfg(feature = "cpurender")]
        {
            let ws = self.common.current_window_state();
            let width = ws.size.dimensions.width;
            let height = ws.size.dimensions.height;
            let dpi = ws.size.dpi as f32 / 96.0;
            // Shared per-frame content preparation (journal clock, image
            // callbacks through the content chokepoint, scrollbar cache).
            // Before this, image callbacks were NEVER invoked on this host —
            // every callback image rendered as the announced grey placeholder.
            if let Some(lw) = self.common.layout_window.as_mut() {
                lw.prepare_frame_cpu();
            }
            if let Some(lw) = self.common.layout_window.as_ref() {
                self.cpu_backend.render_frame(
                    lw,
                    &self.common.renderer_resources,
                    width,
                    height,
                    dpi,
                );
            }
        }
    }

    pub fn regenerate_layout_inner(
        &mut self,
    ) -> Result<crate::desktop::shell2::common::layout::LayoutRegenerateResult, String> {
        // Captured BEFORE the pass: `regenerate_layout` (the trait wrapper that
        // calls this) drains lifecycle callbacks between passes, and one of
        // those returning `Update::RefreshDom` raises a NEW request. Retiring
        // by epoch at the end means this pass only retires the request it
        // actually saw.
        let regen_epoch_seen = self.common.regen_epoch();

        // Consume the reason tag BEFORE borrowing the layout window: this is
        // the regeneration this window asked for, and the tag travels with
        // the request (see CommonWindowState::request_regeneration).
        let relayout_reason = self.common.take_relayout_reason();

        let borrows = self.common.layout_borrows();
        let layout_window = borrows.layout_window.ok_or("No layout window")?;

        let debug_enabled = crate::desktop::shell2::common::debug_server::is_debug_enabled();
        let mut debug_messages = if debug_enabled {
            Some(Vec::new())
        } else {
            None
        };

        let result = crate::desktop::shell2::common::layout::regenerate_layout(
            layout_window,
            borrows.app_data,
            borrows.current_window_state,
            borrows.renderer_resources,
            borrows.gl_context_ptr,
            borrows.fc_cache,
            &self.font_registry,
            borrows.system_style,
            &self.icon_provider,
            &mut debug_messages,
            relayout_reason,
        )?;

        if let Some(msgs) = debug_messages {
            for msg in msgs {
                crate::desktop::shell2::common::debug_server::log(
                    crate::desktop::shell2::common::debug_server::LogLevel::Debug,
                    crate::desktop::shell2::common::debug_server::LogCategory::Layout,
                    msg.message.as_str().to_string(),
                    None,
                );
            }
        }

        // Rebuild CPU hit-tester from new layout results
        if let Some(lw) = self.common.layout_window.as_ref() {
            self.cpu_backend
                .hit_tester
                .rebuild_from_layout_with_gpu(&lw.layout_results, Some(&lw.gpu_state_manager));
        }

        // Also rebuild the SHARED hit-tester that the common event-dispatch path
        // reads (perform_hit_test -> update_hit_test_at). The rebuild above only
        // feeds the render path; POINTER EVENTS resolve their target node
        // through `common.cpu_hit_tester`, which was constructed empty and never
        // repopulated here — so every tap hit-tested to nothing and no widget
        // callback ever fired. The UI rendered perfectly and was completely
        // inert. `headless/mod.rs` already carries this exact fix and the same
        // explanation; both mobile backends were missing the one line.
        self.common.rebuild_cpu_hit_tester();

        // Drain lifecycle events (Mount / AfterMount / Unmount) produced by this
        // layout's reconciliation — the SAME step headless + X11 run. Without it,
        // EventFilter::Component(AfterMount) callbacks never fire on Android (e.g.
        // the MapWidget's first tile fetch never starts).

        // #27 native backbuffer: Android stays LEGACY by design.
        // `ANativeWindow_lock` rotates double/triple buffers with NO content
        // guarantee and no way to preserve a buffer's pixels across cycles
        // (NDK-documented), so the renderer's incremental base would be
        // garbage. Going native needs the Wayland slot model keyed by the
        // returned bits pointer (per-buffer stale tracking + the in/out
        // dirty-bounds contract); design when a device run exists to verify.
        //
        // CPU-render the frame — populates `self.cpu_backend.last_frame`
        // so the next `render_frame()` call can blit pixels.
        self.rerender_cpu();

        // Republish the virtual-view tree. Bounds, labels and the focused node
        // all just changed and TalkBack reads a cached tree, so without this it
        // keeps announcing (and highlighting) the previous layout.
        #[cfg(feature = "a11y")]
        self.refresh_accessibility_tree();

        self.common
            .clear_regeneration_unless_reraised(regen_epoch_seen);
        Ok(result)
    }
}

impl PlatformWindow for AndroidWindow {
    fn regenerate_layout_once(
        &mut self,
    ) -> Result<crate::desktop::shell2::common::layout::LayoutRegenerateResult, String> {
        // The single pass. The bounded lifecycle loop lives in the trait
        // default `regenerate_layout`, which is what frame paths call.
        self.regenerate_layout_inner()
    }

    impl_platform_window_getters!(common);

    fn get_raw_window_handle(&self) -> RawWindowHandle {
        #[cfg(feature = "ndk")]
        let ptr = self
            .native_window
            .as_ref()
            .map(|nw| nw.ptr().as_ptr() as *mut c_void)
            .unwrap_or(std::ptr::null_mut());
        #[cfg(not(feature = "ndk"))]
        let ptr = std::ptr::null_mut();

        RawWindowHandle::Android(AndroidHandle {
            a_native_window: ptr,
        })
    }

    fn prepare_callback_invocation(&mut self) -> event::InvokeSingleCallbackBorrows<'_> {
        let borrows = self.common.layout_borrows();
        event::InvokeSingleCallbackBorrows {
            layout_window: borrows
                .layout_window
                .expect("Layout window must exist for callback invocation"),
            window_handle: RawWindowHandle::Android(AndroidHandle {
                a_native_window: std::ptr::null_mut(),
            }),
            gl_context_ptr: borrows.gl_context_ptr,
            fc_cache_clone: (**borrows.fc_cache).clone(),
            system_style: borrows.system_style.clone(),
            previous_window_state: borrows.previous_window_state,
            current_window_state: borrows.current_window_state,
            renderer_resources: borrows.renderer_resources,
        }
    }

    fn start_timer(&mut self, timer_id: usize, timer: azul_layout::timer::Timer) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            lw.timers
                .insert(azul_core::task::TimerId { id: timer_id }, timer);
        }
    }
    fn stop_timer(&mut self, timer_id: usize) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            lw.timers.remove(&azul_core::task::TimerId { id: timer_id });
        }
    }
    fn start_thread_poll_timer(&mut self) {}
    fn stop_thread_poll_timer(&mut self) {}

    fn add_threads(
        &mut self,
        threads: std::collections::BTreeMap<azul_core::task::ThreadId, azul_layout::thread::Thread>,
    ) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            for (id, thread) in threads {
                lw.threads.insert(id, thread);
            }
        }
    }
    fn remove_threads(
        &mut self,
        thread_ids: &std::collections::BTreeSet<azul_core::task::ThreadId>,
    ) {
        if let Some(lw) = self.common.layout_window.as_mut() {
            for id in thread_ids {
                lw.threads.remove(id);
            }
        }
    }

    fn queue_window_create(&mut self, _options: WindowCreateOptions) {
        // No popup windows on Android; ignored. Sub-activities are a future
        // enhancement and would require launching new Intents from Java.
    }

    fn show_menu_from_callback(
        &mut self,
        _menu: &azul_core::menu::Menu,
        _position: azul_core::geom::LogicalPosition,
        _anchor: Option<azul_core::geom::LogicalRect>,
    ) {
    }

    fn show_tooltip_from_callback(
        &mut self,
        _text: &str,
        _position: azul_core::geom::LogicalPosition,
    ) {
    }

    fn hide_tooltip_from_callback(&mut self) {}

    /// The activity owns the window geometry outright, so there is nothing to
    /// push and no OS-sync baseline to diff (`os_synced_state` stays `None`).
    fn sync_window_state(&mut self) {}
}

// ---------------------------------------------------------------------------
// android_main entry point (called by the NativeActivity glue thread)
// ---------------------------------------------------------------------------

/// `android_main` is the entry point that the `android-activity` crate's
/// `ANativeActivity_onCreate` shim invokes on the Android UI thread.
///
/// The user's `azul_run(app_data, ...)` call stashes `INITIAL_OPTIONS` into a
/// global static *before* the dylib hands control to `ANativeActivity_onCreate`,
/// so by the time we get here the options are ready.
#[cfg(all(target_os = "android", feature = "android-activity"))]
#[no_mangle]
pub fn android_main(app: AndroidApp) {
    log_info!(LogCategory::EventLoop, "[Android] android_main entered");

    // Make the AZ_* knobs reachable at all on this platform.
    //
    // An activity cannot be handed environment variables: `am start` builds an
    // Intent and the process inherits the ZYGOTE's environment, not the
    // shell's. There are ~128 distinct `AZ_*` variables across the engine —
    // every trace flag, dump path and diagnostic — and ALL of them were dead on
    // Android, the platform where debugging is hardest. `AZ_E2E` got a bespoke
    // property alias earlier; adding 127 more would be absurd.
    //
    // So one property carries them all, and they are injected into the real
    // environment so every existing `std::env::var` call site works unchanged:
    //
    //     adb shell setprop debug.az.env 'AZ_E2E=/data/local/tmp/x.json;AZWRITER_SCREEN=backstage-info'
    //
    // Called FIRST in android_main, before any other thread exists — `set_var`
    // is not thread-safe, and this is the only point where that is guaranteed.
    inject_env_from_property();

    // Retrieve initial options stashed by `run()`
    let (app_data, undo_manager, config, fc_cache, font_registry, root_window) = unsafe {
        match crate::desktop::shell2::run::ANDROID_INITIAL_OPTIONS.take() {
            Some(opts) => opts,
            None => {
                log_error!(
                    LogCategory::EventLoop,
                    "[Android] android_main called without INITIAL_OPTIONS set — \
                     did azul_run() run first?",
                );
                return;
            }
        }
    };

    let mut window = match AndroidWindow::new(
        root_window,
        fc_cache,
        config,
        app_data,
        undo_manager,
        font_registry,
    ) {
        Ok(w) => w,
        Err(e) => {
            log_error!(
                LogCategory::EventLoop,
                "[Android] AndroidWindow::new failed: {:?}",
                e
            );
            return;
        }
    };

    // Publish the window address so AzulActivity.onWindowFocusChanged can
    // hand it to NativeGestureBridge. `&mut window` is stable for the
    // duration of this function (window stays on the stack frame). Once
    // AzulActivity has constructed the bridge, the Java side never
    // dereferences the pointer except from JNI callbacks that this same
    // thread eventually processes via MainEvent::InputAvailable.
    ANDROID_WINDOW_PTR.store(
        &mut window as *mut AndroidWindow as i64,
        core::sync::atomic::Ordering::SeqCst,
    );

    // Register the debug/E2E timer. `run()` stashed the receiver; the loop
    // below already calls `process_timers_and_threads()`, which is what drives
    // it — so this one registration is the whole difference between "AZ_E2E
    // queued some tests" and "the ops actually dispatch".
    //
    // Set the scenario with `adb shell setprop debug.az.e2e <path>` (an
    // activity cannot be given an env var). The runner writes its cargo-test
    // style verdict to stderr, which on Android is logcat, and exits the
    // process — so the harness watches for the process to die and reads the
    // result out of the log.
    #[cfg(any(feature = "debug-server", feature = "e2e-scripting"))]
    unsafe {
        if let Some((rx, cm)) = crate::desktop::shell2::run::ANDROID_DEBUG_CHANNEL.take() {
            crate::desktop::shell2::common::debug_server::register_debug_timer(&mut window, rx, cm);
        }
    }

    // Publish the JavaVM + Activity pointers so dll::extra::file_picker
    // (and future native-call paths — permission, soft keyboard) can
    // reach into Java without re-receiving them per call.
    publish_jni_context(&app);

    // Outer driver loop — exits when MainEvent::Destroy clears window.is_open.
    while window.is_open() {
        // Block forever when we have no native surface (background); poll
        // at frame rate when we do (foreground rendering).
        let timeout = {
            #[cfg(feature = "ndk")]
            {
                if window.native_window.is_some() {
                    Some(Duration::from_millis(16))
                } else {
                    None
                }
            }
            #[cfg(not(feature = "ndk"))]
            {
                Some(Duration::from_millis(16))
            }
        };

        app.poll_events(timeout, |event| {
            handle_poll_event(&app, &mut window, event);
        });

        // Timers, Thread writebacks and animations. This call had NO call site
        // on Android at all, so nothing time-driven ever ran here: no Timer
        // fired, no background Thread result was ever collected, and no
        // animation advanced. The 16 ms poll above was already the right place
        // to drive it; it simply was never wired.
        // The bool means "needs REDRAW", not "needs regeneration" — and
        // `process_timers_and_threads` has already called `request_regeneration`
        // ITSELF for the cases that genuinely need a DOM rebuild, guarded by a
        // comment saying exactly why the others must not get one: "we just need
        // a repaint, NOT a full layout() call which would rebuild the DOM from
        // stale application data."
        //
        // Forcing RefreshDom here overrode that decision on every tick. During a
        // scroll the physics timer fires at 16 ms, so this alone re-ran the
        // app's layout() ~60x/second for the whole gesture.
        if window.process_timers_and_threads() {
            window.needs_rerender = true;
        }

        // Accessibility actions arrive off-loop: TalkBack calls
        // `AccessibilityNodeProvider.performAction` on the Java UI thread, which
        // only QUEUES the action (mutating the LayoutWindow from there would
        // race this loop). This is where they get applied — the same per-frame
        // slot `run.rs` gives the four desktop backends.
        #[cfg(feature = "a11y")]
        window.process_accessibility_actions();

        // Regenerate layout when something invalidated the frame (init,
        // resize, input). Populates cpu_backend.last_frame.
        // Drain the Java-thread theme queue on the loop thread: snapshot →
        // mutate → pass, like every other OS-state change.
        drain_pending_theme(&mut window);

        // NATIVE SELECTION TOOLBAR (U2). Android owns the floating
        // Cut/Copy/Paste bar; the engine owns the selection. This is the join,
        // and it did not exist - `startSelectionToolbar` had no caller at all,
        // so the bar has never appeared however complete the Java looked.
        //
        // Driven off the ENGINE's selection rather than a gesture, because
        // that is the thing that is actually true: a selection made by a
        // double-tap, by Select All, or by a remote participant's edit all
        // deserve the same bar.
        {
            let lw = window.common.layout_window.as_ref();
            let has_selection = lw
                .and_then(azul_layout::window::LayoutWindow::focused_selection_byte_range)
                .is_some_and(|(start, end)| start != end);
            // HIDDEN WHILE A HANDLE IS DRAGGED (U2-a-ii), shown again on release
            // - what Android's own text fields do, and for the same reason: the
            // bar floats over the selection, and a selection being resized under
            // a finger has a bar in the way. This is a TRANSITION hook, so
            // folding the drag into the "wanted" bit is the whole change: the
            // press flips it off (stopSelectionToolbar), the release flips it
            // back on (startSelectionToolbar, positioned by `onGetContentRect`
            // against the new range). No Java change - the drag never has to
            // be surfaced to the Java side after all.
            let handle_dragging =
                lw.is_some_and(azul_layout::window::LayoutWindow::selection_handle_drag_active);
            let has_selection = has_selection && !handle_dragging;
            if has_selection != window.selection_toolbar_shown {
                let native_ptr = core::ptr::from_mut(&mut window) as i64;
                set_selection_toolbar_visible(has_selection, native_ptr);
                window.selection_toolbar_shown = has_selection;
            }
        }

        // The soft-keyboard drain moved to `process_window_events` (10a-iv),
        // where it now serves BOTH the app's explicit request and the
        // focus-driven raise through one queue. A second drain here would race
        // it: whichever ran first would consume the request and the other
        // would see nothing.

        // Selection-toolbar actions, on the LOOP thread for the same reason as
        // the IME queue below: they arrive from Android's ActionMode on the UI
        // thread, and a system change has to be applied where the loop sees it.
        {
            let actions: Vec<i32> = window
                .pending_selection_actions
                .lock()
                .map(|mut q| core::mem::take(&mut *q))
                .unwrap_or_default();
            for action in actions {
                use azul_core::events::SystemChange;
                // Cut names the node it cuts FROM; the others operate on the
                // current selection. Without a focused node there is nothing
                // to cut, so skip rather than invent a target.
                let focused = window
                    .common
                    .layout_window
                    .as_ref()
                    .and_then(|lw| lw.focus_manager.get_focused_node().copied());
                let change = match (action, focused) {
                    (0, Some(target)) => SystemChange::CutToClipboard { target },
                    (1, _) => SystemChange::CopyToClipboard,
                    (2, _) => SystemChange::PasteFromClipboard,
                    (3, _) => SystemChange::SelectAllText,
                    _ => continue,
                };
                window.snapshot_window_state_baseline("android.selection_action");
                let r = window.apply_system_change(&change);
                log_info!(
                    LogCategory::Input,
                    "[Android] selection action {} -> {:?}",
                    action,
                    r
                );
                if !matches!(r, azul_core::events::ProcessEventResult::DoNothing) {
                    window.needs_rerender = true;
                }
            }
        }

        // Apply IME text on the LOOP thread. `record_text_input` stages a
        // changeset; the event pass right after is what turns it into
        // `ApplyPendingTextInput` -> `ApplyTextChangeset` and, for an editable
        // subtree, the `DocumentEdit` the app subscribes to. Staging without a
        // pass — which is what this did — left the text recorded and never
        // applied, so the IME composed, committed, and nothing appeared.
        {
            let commits: Vec<String> = window
                .pending_ime_commits
                .lock()
                .map(|mut q| core::mem::take(&mut *q))
                .unwrap_or_default();
            for text in commits {
                window.snapshot_window_state_baseline("android.ime_commit");
                if let Some(lw) = window.common.layout_window.as_mut() {
                    // Commit, not clear: this carries the committed string so
                    // CompositionEnd can report it, exactly as the desktop
                    // shells do.
                    lw.text_edit_manager.commit_composition(text.clone());
                    let _ = lw.record_text_input(&text);
                }
                let r = window.process_window_events(0);
                log_info!(
                    LogCategory::Input,
                    "[Android] IME applied {:?} -> {:?} (relayout_only={}, regen={})",
                    text,
                    r,
                    window.common.relayout_only_pending(),
                    window.common.regeneration_pending(),
                );
                // Same ladder as the input sites: an IME commit reports
                // ShouldIncrementalRelayout, which must be PERFORMED here, not
                // escalated into a DOM rebuild that discards it.
                match r {
                    azul_core::events::ProcessEventResult::ShouldIncrementalRelayout => {
                        let mut dbg = None;
                        if let Err(e) = window.incremental_relayout_dispatching(
                            crate::desktop::shell2::common::event::IncrementalRelayout::Restyle,
                            &mut dbg,
                        ) {
                            log_error!(
                                LogCategory::Layout,
                                "[Android] IME incremental relayout failed: {}",
                                e
                            );
                        }
                        window.common.request_relayout_only();
                        window.needs_rerender = true;
                    }
                    azul_core::events::ProcessEventResult::ShouldRegenerateDomCurrentWindow
                    | azul_core::events::ProcessEventResult::ShouldRegenerateDomAllWindows => {
                        window
                            .common
                            .request_regeneration(RelayoutReason::RefreshDom);
                    }
                    azul_core::events::ProcessEventResult::DoNothing => {}
                    _ => window.needs_rerender = true,
                }
            }
        }

        // Relayout-only, checked FIRST — the same order macOS and Wayland use.
        // An incremental relayout (restyle, runtime text edit) already re-ran
        // layout and rebuilt the display list; running `regenerate_layout` on
        // top would discard it and re-invoke the app's layout_callback. The
        // input arm raises BOTH flags, so this must be tested before the plain
        // regeneration request or the skip never happens.
        let relayout_only = window.common.take_relayout_only();
        if relayout_only {
            log_info!(
                LogCategory::Layout,
                "[Android] relayout-only: skipping regenerate_layout, repainting"
            );
            window.needs_rerender = true;
            window
                .common
                .clear_regeneration_unless_reraised(window.common.regen_epoch());
        }

        let mut frame_dirty = false;
        if window.common.regeneration_pending() {
            // A regeneration re-rasters on its way through, so a redraw request
            // raised earlier in the same iteration is already satisfied.
            window.needs_rerender = false;
            match window.regenerate_layout() {
                Ok(_) => frame_dirty = true,
                Err(e) => {
                    log_error!(
                        LogCategory::Layout,
                        "[Android] regenerate_layout failed: {}",
                        e
                    );
                }
            }
        } else if window.needs_rerender {
            // Repaint only: the pixels changed (a scroll offset, a hover
            // restyle), the layout did not. No app callback, no solve.
            window.needs_rerender = false;
            window.rerender_cpu();
            frame_dirty = true;
        }

        // Present ONLY when this iteration produced a frame. The loop wakes
        // every 16 ms for timers, and presenting unconditionally locked,
        // full-copied (~10 MB at 1080p RGBA) and unlockAndPost'ed an
        // identical buffer on every wake — keeping SurfaceFlinger compositing
        // at 60 Hz while the app sat idle. Everything that changes what is on
        // screen funnels through request_regeneration (input, timers, thread
        // writebacks, a11y, InitWindow, RedrawNeeded), so a clean iteration
        // has nothing new to post.
        if frame_dirty {
            let _ = render_frame(&mut window);
        }
    }

    log_info!(
        LogCategory::EventLoop,
        "[Android] android_main exiting cleanly"
    );
}

/// The reason tag for a geometry/density-driven regeneration.
///
/// `Resize` is what every desktop backend tags window resizes with — it is the
/// variant responsive layout callbacks branch on (see the enum's own doc) —
/// and Android tagged them all `RefreshDom`, so a breakpoint-style layout
/// could never distinguish a rotation from an app-state change. The one
/// exception is the very first pass: `RegenerationState::pending_initial` is
/// already queued as `Initial` and the user's layout callback must see THAT,
/// so return the implicit `RefreshDom` (which `request_regeneration` never
/// lets overwrite a more specific queued reason) while it is still pending.
/// Apply a theme change queued by the Java UI thread (see `pending_theme`).
/// Runs on the loop thread: contract shape (snapshot → mutate → pass), so
/// `ThemeChanged` dispatches and no live delta is left behind.
#[cfg(all(target_os = "android", feature = "android-activity"))]
fn drain_pending_theme(window: &mut AndroidWindow) {
    let raw = window
        .pending_theme
        .swap(0, std::sync::atomic::Ordering::AcqRel);
    let theme = match raw {
        1 => azul_core::window::WindowTheme::LightMode,
        2 => azul_core::window::WindowTheme::DarkMode,
        _ => return,
    };
    if window.common.current_window_state().theme == theme {
        return;
    }
    window.snapshot_window_state_baseline("android.drain_pending_theme");
    window.common.update_unsynced_state(|ws| ws.theme = theme);
    window
        .common
        .request_regeneration(RelayoutReason::ThemeChange);
    let _ = window.process_window_events(0);
}

#[cfg(all(target_os = "android", feature = "android-activity"))]
fn resize_reason(window: &AndroidWindow) -> RelayoutReason {
    if window.common.regeneration_pending()
        && window.common.regeneration_reason() == RelayoutReason::Initial
    {
        RelayoutReason::RefreshDom
    } else {
        RelayoutReason::Resize
    }
}

#[cfg(all(target_os = "android", feature = "android-activity"))]
fn handle_poll_event(app: &AndroidApp, window: &mut AndroidWindow, event: PollEvent<'_>) {
    match event {
        PollEvent::Main(main_event) => match main_event {
            MainEvent::InitWindow { .. } => {
                // Contract shape (snapshot → mutate → pass): Android never
                // dispatched WindowResize/WindowDpiChanged — these arms wrote
                // geometry with no snapshot and no pass, so the diff either
                // never existed or tripped the validation check later.
                window.snapshot_window_state_baseline("android.main_event.init_window");
                // Sync the framework's window state to the native
                // surface: physical dimensions + DPI. azul-layout uses
                // 96 as the "1x" baseline (CSS pixel = 1/96 inch), so
                // Android's density-dpi (160 = mdpi = 1x) must be
                // scaled by 96/160 = 0.6 before we hand it over:
                //   mdpi 160 -> 96, xhdpi 320 -> 192, xxhdpi 480 -> 288.
                // The drain_input physical-to-logical scale below
                // separately uses density / 160 directly (which is the
                // Android-native scale factor, not the framework's).
                let density = app.config().density().filter(|&d| d > 0).unwrap_or(160);
                let dpi = ((density as f32) * 96.0 / 160.0).round() as u32;
                window
                    .common
                    .update_window_state(event::WindowStateSource::Os, |ws| {
                        ws.size.dpi = dpi.max(1);
                    });
                #[cfg(feature = "ndk")]
                {
                    if let Some(nw) = app.native_window() {
                        // Logical = physical / android-scale, where
                        // android-scale = density / 160 (NOT dpi/96).
                        let android_scale = (density as f32) / 160.0;
                        let logical_w = (nw.width() as f32) / android_scale;
                        let logical_h = (nw.height() as f32) / android_scale;
                        log_debug!(
                            LogCategory::Window,
                            "[Android] InitWindow physical={}x{} density={} (azul dpi={}) logical={}x{}",
                            nw.width(), nw.height(), density, dpi, logical_w, logical_h,
                        );
                        window
                            .common
                            .update_window_state(event::WindowStateSource::Os, |ws| {
                                ws.size.dimensions.width = logical_w;
                                ws.size.dimensions.height = logical_h;
                            });
                        window.native_window = Some(nw);
                        // On the launch InitWindow this preserves the queued
                        // `Initial`; on a re-attach (rotation recreates the
                        // surface with new dimensions and does NOT deliver
                        // WindowResized) it tags the pass `Resize`.
                        let reason = resize_reason(window);
                        window.common.request_regeneration(reason);
                    }
                }
                let _ = window.process_window_events(0);
            }
            MainEvent::TerminateWindow { .. } => {
                log_debug!(LogCategory::Window, "[Android] TerminateWindow");
                #[cfg(feature = "ndk")]
                {
                    window.native_window = None;
                }
            }
            MainEvent::WindowResized { .. } => {
                // Contract shape (snapshot → mutate → pass) — see InitWindow.
                window.snapshot_window_state_baseline("android.main_event.window_resized");
                #[cfg(feature = "ndk")]
                {
                    if let Some(nw) = window.native_window.as_ref() {
                        let density = app.config().density().filter(|&d| d > 0).unwrap_or(160);
                        let android_scale = (density as f32) / 160.0;
                        window
                            .common
                            .update_window_state(event::WindowStateSource::Os, |ws| {
                                ws.size.dimensions.width = (nw.width() as f32) / android_scale;
                                ws.size.dimensions.height = (nw.height() as f32) / android_scale;
                            });
                    }
                }
                let reason = resize_reason(window);
                window.common.request_regeneration(reason);
                let _ = window.process_window_events(0);
            }
            MainEvent::ConfigChanged { .. } => {
                // Density can change while running: fold/unfold, moving the
                // app to an external display, the user's display-size setting.
                // WindowResized alone misses pure-density changes (same
                // surface size, different scale), which left every
                // physical<->logical conversion — layout dpi, input scaling,
                // a11y bounds — on the stale factor.
                let density = app.config().density().filter(|&d| d > 0).unwrap_or(160);
                let dpi = (((density as f32) * 96.0 / 160.0).round() as u32).max(1);
                if window.common.current_window_state().size.dpi != dpi {
                    // Contract shape (snapshot → mutate → pass) — the dpi
                    // diff is what dispatches WindowDpiChanged.
                    window.snapshot_window_state_baseline("android.main_event.config_changed");
                    let reason = resize_reason(window);
                    window
                        .common
                        .update_window_state(event::WindowStateSource::Os, |ws| {
                            ws.size.dpi = dpi;
                        });
                    #[cfg(feature = "ndk")]
                    if let Some(nw) = window.native_window.as_ref() {
                        let android_scale = (density as f32) / 160.0;
                        window
                            .common
                            .update_window_state(event::WindowStateSource::Os, |ws| {
                                ws.size.dimensions.width = (nw.width() as f32) / android_scale;
                                ws.size.dimensions.height = (nw.height() as f32) / android_scale;
                            });
                    }
                    window.common.request_regeneration(reason);
                    let _ = window.process_window_events(0);
                }
            }
            MainEvent::InputAvailable => {
                drain_input(app, window);
            }
            MainEvent::RedrawNeeded { .. } => {
                // The system needs the window's content re-posted (resume,
                // compositor state loss). Presents are gated on regeneration,
                // so raise the request — the regenerate takes the incremental
                // "nothing changed" path and the blit re-posts the pixmap.
                window
                    .common
                    .request_regeneration(RelayoutReason::RefreshDom);
            }
            MainEvent::Destroy => {
                window.close();
            }
            MainEvent::Pause | MainEvent::Resume { .. } => {
                // No-op for now; future: pause timers, stop animations.
            }
            _ => {}
        },
        _ => {}
    }
}

/// Drain the input queue once. Maps the first pointer of every motion event
/// to the mouse left button — enough for hover/click in the existing event
/// system; multi-touch (`TouchStart`/`TouchMove`/`TouchEnd`) is deferred.
#[cfg(all(target_os = "android", feature = "android-activity"))]
fn drain_input(app: &AndroidApp, window: &mut AndroidWindow) {
    use azul_core::geom::LogicalPosition;
    use azul_core::window::CursorPosition;

    let mut iter = match app.input_events_iter() {
        Ok(it) => it,
        Err(e) => {
            // Promoted from debug: "no input queue" is the difference between
            // a live UI and a picture of one, and it was invisible at the
            // default log level.
            log_info!(
                LogCategory::Input,
                "[Android] input_events_iter FAILED: {:?} — no touch will ever arrive",
                e
            );
            return;
        }
    };

    // dpi factor: device pixels per logical px. Android's baseline
    // density is 160 dpi (mdpi); a 480-dpi xxhdpi screen returns 480,
    // so logical = physical * (160/480) = physical * 0.333. Fall back
    // to 1.0 on the rare device that returns no density.
    let dpi = match app.config().density() {
        Some(d) if d > 0 => (d as f32) / 160.0_f32,
        _ => 1.0_f32,
    };

    // Collect state-update tuples first; do the actual state diff +
    // process_window_events outside the iterator's closure because the
    // closure borrows `app` for the input queue and we need &mut window.
    //
    // `mouse_pos` mirrors what the framework's mouse pipe sees: the
    // primary (index 0) pointer position. Multi-finger state lives on
    // `touch_points` below.
    struct MotionUpdate {
        action: MotionAction,
        mouse_pos: LogicalPosition,
        touch_points: Vec<azul_core::window::TouchPoint>,
        /// `MotionEvent.getDeviceId()`: which physical device produced this,
        /// for `MouseState::pointer_device_id` (9b-ii). Android has ONE
        /// cursor, so this names the device driving the primary seat and
        /// never a second seat.
        device_id: u64,
    }
    let mut motion_updates: Vec<MotionUpdate> = Vec::new();
    // (KeyAction, Option<VirtualKeyCode>) — None for unmapped keycodes.
    // The third element is Android's SCAN CODE, which is the raw evdev code:
    // Android input sits on evdev, so `PhysicalKey::from_evdev` reads it
    // directly. It is 0 for a soft-keyboard/IME event, which has no physical
    // key behind it — and evdev 0 is `KEY_RESERVED`, so the table already
    // answers `Unidentified` for exactly that case.
    let mut key_updates: Vec<(
        KeyAction,
        Option<azul_core::window::VirtualKeyCode>,
        i32,
        bool,
    )> = Vec::new();
    // Pen / stylus samples — populated when any pointer in a MotionEvent
    // reports `ToolType::Stylus` or `ToolType::Eraser`. tilt is decomposed
    // into (x_tilt_deg, y_tilt_deg) so it matches the W3C
    // `PointerEvent.tiltX/tiltY` shape that the desktop pen-tablet path
    // uses too.
    struct PenSample {
        action: MotionAction,
        pos: LogicalPosition,
        pressure: f32,
        x_tilt_deg: f32,
        y_tilt_deg: f32,
        is_eraser: bool,
        barrel_button_pressed: bool,
    }
    let mut pen_updates: Vec<PenSample> = Vec::new();
    /// Wear-crown rotation samples, in `AXIS_SCROLL` units (detents), with
    /// the device that produced them - the resolution is per DEVICE.
    let mut rotary_deltas: Vec<(i32, f32)> = Vec::new();

    while iter.next(|event| {
        match event {
            InputEvent::MotionEvent(m) => {
                // A WEAR CROWN is a MotionEvent too, and it is not a pointer:
                // `SOURCE_ROTARY_ENCODER` reports rotation on `AXIS_SCROLL`
                // with no coordinates at all. Handled first and returned
                // early, because everything below treats a MotionEvent as
                // touch/mouse input and would fabricate a pointer at (0, 0)
                // from an event that has no position.
                //
                // `DialState` names this platform in its own docs as one of
                // the four that converged on the dial primitive; it simply had
                // no producer here.
                if m.source() == android_activity::input::Source::RotaryEncoder {
                    let scroll = m
                        .pointers()
                        .next()
                        .map_or(0.0, |p| p.axis_value(Axis::Scroll));
                    if scroll != 0.0 {
                        rotary_deltas.push((m.device_id(), scroll));
                    }
                    // Collected, not applied: this closure only gathers, and
                    // the window is mutated after the loop like every other
                    // input family here.
                    return InputStatus::Handled;
                }

                let mut mouse_pos = LogicalPosition::new(0.0, 0.0);
                let mut touch_points: Vec<azul_core::window::TouchPoint> = Vec::new();
                let mut first_pointer = true;

                // ACTION_POINTER_UP still lists the LIFTING finger in
                // pointers() — the classic index-vs-id trap's sibling. Keep it
                // out of touch_state or the lifted finger stays "touching"
                // until the next MOVE happens to rebuild the list.
                // MotionEvent::pointer_index() identifies which pointer the
                // action is about (only meaningful for the Down/Up family).
                let lifted_index = if matches!(m.action(), MotionAction::PointerUp) {
                    Some(m.pointer_index())
                } else {
                    None
                };

                for p in m.pointers() {
                    // Window-relative coordinates (AMotionEvent_getX/getY), NOT
                    // raw_x/raw_y: raw is DISPLAY-relative, so in split-screen /
                    // freeform / pop-up multi-window the window's offset shifted
                    // every touch and hit tests landed on the wrong node. The
                    // surface we render into lives in window space; getX/getY is
                    // the matching input space (they only coincide when the
                    // window sits at the display origin).
                    let pos = LogicalPosition::new(p.x() / dpi, p.y() / dpi);
                    if first_pointer {
                        mouse_pos = pos;
                        first_pointer = false;
                    }

                    // The finger this PointerUp is about is lifting — it still
                    // appears in pointers(), but it is no longer touching.
                    // (Stylus lift is handled separately below via the action.)
                    if Some(p.pointer_index()) != lifted_index {
                        let pressure = p.pressure();
                        let force = if pressure > 0.0 && pressure <= 1.0 {
                            pressure
                        } else {
                            0.5 // TouchPoint sentinel for "pressure not available"
                        };
                        touch_points.push(azul_core::window::TouchPoint {
                            id: p.pointer_id() as u64,
                            position: pos,
                            force,
                            // Contact geometry: 0.0 = not reported by this backend.
                            major: 0.0,
                            minor: 0.0,
                            orientation_rad: 0.0,
                            tool_type: azul_core::window::TouchToolType::Unknown,
                        });
                    }

                    let tool = p.tool_type();
                    if matches!(tool, ToolType::Stylus | ToolType::Eraser) {
                        let pressure = p.pressure().clamp(0.0, 1.0);
                        let tilt_rad = p.axis_value(Axis::Tilt);
                        let orientation = p.axis_value(Axis::Orientation);
                        let (sin_o, cos_o) = orientation.sin_cos();
                        let tan_tilt = tilt_rad.tan();
                        let x_tilt_deg = (sin_o * tan_tilt).atan().to_degrees();
                        let y_tilt_deg = (-cos_o * tan_tilt).atan().to_degrees();
                        pen_updates.push(PenSample {
                            action: m.action(),
                            pos,
                            pressure,
                            x_tilt_deg,
                            y_tilt_deg,
                            is_eraser: matches!(tool, ToolType::Eraser),
                            barrel_button_pressed: m.button_state().stylus_primary(),
                        });
                    }
                }

                if !first_pointer {
                    motion_updates.push(MotionUpdate {
                        action: m.action(),
                        mouse_pos,
                        touch_points,
                        device_id: u64::from(m.device_id().unsigned_abs()),
                    });
                }
            }
            InputEvent::KeyEvent(k) => {
                key_updates.push((
                    k.action(),
                    map_keycode(k.key_code()),
                    k.scan_code(),
                    // Android counts repeats on the event itself, so unlike
                    // X11/Wayland this needs no inference from held state.
                    k.repeat_count() > 0,
                ));
            }
            _ => {}
        }
        // unicode_char mapping (KeyCharacterMap) still TODO — gets us
        // text input from a hardware keyboard. State-diff already fires
        // VirtualKeyDown / VirtualKeyUp HoverEventFilters from the
        // current_virtual_keycode change below, which is enough for the
        // most common test cases (Enter to submit, Tab to navigate).
        InputStatus::Unhandled
    }) {}

    log_debug!(
        LogCategory::Input,
        "[Android] drain_input: {} motion, {} key, {} pen",
        motion_updates.len(),
        key_updates.len(),
        pen_updates.len(),
    );

    for update in motion_updates {
        // Snapshot previous state — required by the state-diffing event system.
        window.snapshot_window_state_baseline("android.drain_input.motion");

        {
            let ms = window.common.mouse_state_mut();
            // The field existed with no writer on any platform, so
            // `get_pointer_device_id()` answered 0 everywhere (9b-ii).
            ms.pointer_device_id = update.device_id;
            match update.action {
                MotionAction::Down | MotionAction::PointerDown => {
                    ms.cursor_position = CursorPosition::InWindow(update.mouse_pos);
                    ms.left_down = true;
                }
                MotionAction::Move | MotionAction::HoverMove => {
                    ms.cursor_position = CursorPosition::InWindow(update.mouse_pos);
                }
                MotionAction::Up | MotionAction::Cancel => {
                    ms.left_down = false;
                }
                MotionAction::PointerUp => {
                    // A secondary finger lifted; primary is still down.
                    // Leave left_down alone.
                }
                _ => {}
            }

            // Refresh TouchState. Android delivers all currently-active
            // pointers on every MotionEvent, so the rebuild is
            // straightforward (no need for the per-ID merge iOS does).
            let ts = window.common.touch_state_mut();
            match update.action {
                MotionAction::Up | MotionAction::Cancel => {
                    // Last finger lifted — clear.
                    ts.touch_points = azul_core::window::TouchPointVec::from_const_slice(&[]);
                }
                _ => {
                    ts.touch_points =
                        azul_core::window::TouchPointVec::from_vec(update.touch_points);
                }
            }
            ts.num_touches = ts.touch_points.len();
        }

        // Update CPU hit-tester at the new cursor; dispatch callbacks.
        window.update_hit_test_at(update.mouse_pos);

        // ONE-FINGER PAN -> SCROLL.
        //
        // Neither mobile backend translated touch drags into scrolling at all:
        // a drag only moved `cursor_position` and set `left_down`, which the
        // engine reads as a mouse drag. Nothing produced
        // `ScrollInputDevice::Touchscreen`, even though the variant has existed
        // (documented "Direct touchscreen panning") the whole time — so the
        // single most basic mobile gesture did nothing.
        //
        // Funnelled through `record_scroll_from_hit_test` like every desktop
        // backend, so the gesture latch, nested-container handoff and
        // rubber-band physics are the same code. It must run AFTER
        // `update_hit_test_at` (it reads the hover manager) and BEFORE
        // `process_window_events`, which is where the shared site arms the
        // physics timer.
        //
        // `TrackpadContinuous` is the processing model — a finger sets the
        // position directly, exactly like a precise trackpad, rather than the
        // velocity impulse a ratcheting wheel gets. `TrackpadEnd` on lift is
        // what hands an overshoot to the spring.
        {
            use azul_core::task::Instant;
            use azul_layout::managers::hover::InputPointId;
            use azul_layout::managers::scroll_state::{ScrollInputDevice, ScrollInputSource};

            let (delta, source) = match update.action {
                MotionAction::Down | MotionAction::PointerDown => {
                    window.touch_pan_last = Some(update.mouse_pos);
                    (None, ScrollInputSource::TrackpadContinuous)
                }
                MotionAction::Move => {
                    let d = window.touch_pan_last.map(|last| {
                        // Finger delta, NOT the inverse. Dragging UP must move
                        // the content up (revealing what is below), i.e. the
                        // scroll offset INCREASES — and `record_scroll_input`
                        // already applies the natural-scroll sign centrally, so
                        // inverting here too cancels out: measured on device,
                        // `last - current` drove the offset negative and
                        // rubber-banded against the top edge instead of
                        // scrolling.
                        (update.mouse_pos.x - last.x, update.mouse_pos.y - last.y)
                    });
                    window.touch_pan_last = Some(update.mouse_pos);
                    (d, ScrollInputSource::TrackpadContinuous)
                }
                MotionAction::Up | MotionAction::Cancel => {
                    window.touch_pan_last = None;
                    // Zero delta, but the END phase still matters: it is what
                    // releases a rubber-banded axis back to its bounds.
                    (Some((0.0, 0.0)), ScrollInputSource::TrackpadEnd)
                }
                _ => (None, ScrollInputSource::TrackpadContinuous),
            };

            if let Some((dx, dy)) = delta {
                let ended = source == ScrollInputSource::TrackpadEnd;
                if ended || dx.abs() > 0.01 || dy.abs() > 0.01 {
                    let now = Instant::from(std::time::Instant::now());
                    if let Some(lw) = window.common.layout_window.as_mut() {
                        let _ = lw.scroll_manager.record_scroll_from_hit_test(
                            dx,
                            dy,
                            source,
                            ScrollInputDevice::Touchscreen,
                            &lw.hover_manager,
                            &InputPointId::Mouse,
                            now,
                        );
                    }
                }
            }
        }

        let r = window.process_window_events(0);
        log_debug!(
            LogCategory::Input,
            "[Android] motion {:?} at {:?} -> {:?}",
            update.action,
            update.mouse_pos,
            r,
        );
        // HONOUR THE ESCALATION LADDER. Collapsing every non-DoNothing result
        // into `RefreshDom` re-ran the APP's `layout()` callback for a scroll —
        // the heaviest level (5) for an event the engine classified as level
        // 1-2. `common/event.rs` documents the same trap on the autoscroll
        // timer: "Returning RefreshDom re-invoked the APP's layout() callback
        // every 16ms for the entire duration of a drag-autoscroll." Measured on
        // AzWriter: 121-443 ms per scroll frame escalated, ~6 ms honoured.
        //
        // Same split the four desktop backends use — heavy reasons regenerate,
        // light ones only repaint.
        use azul_core::events::ProcessEventResult as PER;
        match r {
            PER::ShouldRegenerateDomCurrentWindow | PER::ShouldRegenerateDomAllWindows => {
                window
                    .common
                    .request_regeneration(RelayoutReason::RefreshDom);
            }
            // NOT a DOM rebuild. The pass has ALREADY re-run layout on the
            // existing StyledDom and refreshed the per-DOM display list — that
            // is what "incremental" means. Calling `regenerate_layout` here
            // would throw that work away and re-invoke the app's
            // `layout_callback`, rebuilding the DOM from application data that
            // has not caught up yet: an IME commit landed in the engine's
            // StyledDom and was then overwritten by the app's unchanged model,
            // so typing composed, committed, and vanished.
            // The pass CLASSIFIED this as incremental; it did not perform it.
            // Somebody has to run `incremental_relayout` on the existing
            // StyledDom and then declare relayout-only so the frame path skips
            // `regenerate_layout`. macOS does exactly this in
            // `apply_incremental_relayout_result`; Android did neither, so a
            // committed IME string was re-laid-out from the app's unchanged
            // model and vanished.
            PER::ShouldIncrementalRelayout => {
                let mut dbg = None;
                if let Err(e) = window.incremental_relayout_dispatching(
                    crate::desktop::shell2::common::event::IncrementalRelayout::Restyle,
                    &mut dbg,
                ) {
                    log_error!(
                        LogCategory::Layout,
                        "[Android] incremental relayout failed: {}",
                        e
                    );
                }
                window.common.request_relayout_only();
                window.needs_rerender = true;
            }
            PER::UpdateHitTesterAndProcessAgain
            | PER::ShouldUpdateDisplayListCurrentWindow
            | PER::ShouldReRenderCurrentWindow => {
                window.needs_rerender = true;
            }
            PER::DoNothing => {}
        }
    }

    // Apply Wear-crown rotation. A crown is a dial, not a pointer:
    // `SOURCE_ROTARY_ENCODER` reports on `AXIS_SCROLL` with no coordinates,
    // which is why the collector above returns before the touch/mouse path
    // rather than letting it fabricate a pointer at (0, 0).
    //
    // `DialState` names Android's rotary encoder in its own docs as one of the
    // four platforms that converged on the dial primitive - it simply had no
    // producer here, so a crown turned and nothing in the engine heard it.
    //
    // Samples are SUMMED rather than applied one at a time: several arrive per
    // frame on a fast spin, and `update_dial_state` arms one `DialRotate` per
    // call, so applying each would fire a burst of events for one gesture.
    let rotary_total: f32 = rotary_deltas.iter().map(|(_, d)| *d).sum();
    // The device is the same for every sample in one frame; the last one's is
    // as good as any and avoids a lookup per sample.
    let rotary_device = rotary_deltas.last().map_or(0, |(id, _)| *id);
    if rotary_total != 0.0 {
        if let Some(lw) = window.common.layout_window.as_mut() {
            lw.gesture_drag_manager.update_dial_state(
                azul_layout::managers::gesture::DialState {
                    // Wear has one crown, and Android gives it no id.
                    device_id: 0,
                    // RADIANS, WHEN THE DEVICE SAYS SO (9c-i-a). The old
                    // note here claimed Android documents no
                    // radians-per-detent constant. It documents exactly that,
                    // just not where a rotary-input guide would look:
                    // `InputDevice.MotionRange.getResolution()` is "units per
                    // millimeter, or units per RADIAN for rotational axes",
                    // and `AXIS_SCROLL` on a rotary encoder is rotational.
                    //
                    // So the constant comes from the DEVICE rather than from a
                    // guess, which is what makes it honest on hardware nobody
                    // here has. A device that does not report one returns 0
                    // and `delta_rad` stays 0.0 - the previous behaviour, now
                    // the fallback rather than the rule.
                    delta_rad: rotary_scroll_to_radians(rotary_device, rotary_total),
                    // Fractional on a high-resolution crown, which is exactly
                    // what the field documents.
                    detent_count: rotary_total,
                    // A crown PRESS is not deliverable to an app on Wear -
                    // see 9c-i-b, which settles that with Google's own docs
                    // rather than leaving it looking unfinished.
                    pressed: false,
                    // Never on-screen; that is a Surface Studio property.
                    contact_position: azul_core::geom::OptionLogicalPosition::None,
                },
            );
        }
        let r = window.process_window_events(0);
        if !matches!(r, azul_core::events::ProcessEventResult::DoNothing) {
            window.needs_rerender = true;
        }
    }

    // Apply pen samples. Run *after* the motion-state diff so the
    // mouse-pipe view of the world (left_down, cursor_position) is
    // already up-to-date by the time gesture-detection in the callback
    // reads it.
    for sample in pen_updates {
        let in_contact = matches!(sample.action, MotionAction::Down | MotionAction::Move);
        if let Some(lw) = window.common.layout_window.as_mut() {
            if in_contact {
                lw.gesture_drag_manager.update_pen_state(
                    sample.pos,
                    sample.pressure,
                    (sample.x_tilt_deg, sample.y_tilt_deg),
                    true,
                    sample.is_eraser,
                    sample.barrel_button_pressed,
                    0, // device_id — Android has no stable per-device cookie at this layer
                );
            } else {
                lw.gesture_drag_manager.clear_pen_state();
            }
            window
                .common
                .request_regeneration(RelayoutReason::RefreshDom);
        }
    }

    // Apply collected key updates.
    for (action, vkc, scan_code, is_repeat) in key_updates {
        window.snapshot_window_state_baseline("android.drain_input.key");
        {
            let ks = window.common.keyboard_state_mut();
            match (action, vkc) {
                (KeyAction::Down, Some(code)) => {
                    ks.current_virtual_keycode = Some(code).into();
                    // Add to pressed set if not already present (no
                    // VirtualKeyCodeVec dedup API exposed; rely on the
                    // event-determination to dedupe).
                    let mut v = ks.pressed_virtual_keycodes.clone().into_library_owned_vec();
                    if !v.iter().any(|c| *c == code) {
                        v.push(code);
                    }
                    ks.pressed_virtual_keycodes = v.into();
                }
                (KeyAction::Up, Some(code)) => {
                    ks.current_virtual_keycode = None.into();
                    let mut v = ks.pressed_virtual_keycodes.clone().into_library_owned_vec();
                    v.retain(|c| *c != code);
                    ks.pressed_virtual_keycodes = v.into();
                }
                _ => {}
            }

            // Whether THIS event is an auto-repeat. `repeat_count` is 0 for
            // the initial press and counts up while the key is held, so any
            // nonzero value is a repeat. A release always reports 0, which is
            // correct — a release is never a repeat.
            ks.is_repeat = is_repeat && matches!(action, KeyAction::Down);

            // The PHYSICAL position, which the Android keycode cannot answer:
            // that is the LOGICAL key, so binding a game's "forward" to it
            // gives the wrong physical key on every non-US layout — the exact
            // failure `PhysicalKey` exists to prevent, which is why this reads
            // the scan code rather than deriving a position from `vkc`.
            ks.current_physical_key = if matches!(action, KeyAction::Down) {
                azul_core::window::OptionPhysicalKey::Some(
                    azul_core::window::PhysicalKey::from_evdev(scan_code.max(0) as u32),
                )
            } else {
                azul_core::window::OptionPhysicalKey::None
            };

            // `pressed_scancodes` was never filled on Android either, for the
            // same reason: the scan code was not carried this far. It is the
            // same datum, so it is filled here rather than left as a second
            // gap behind the one being closed.
            if scan_code > 0 {
                let sc = scan_code as u32;
                if matches!(action, KeyAction::Down) {
                    ks.pressed_scancodes.insert_hm_item(sc);
                } else {
                    ks.pressed_scancodes.remove_hm_item(&sc);
                }
            }

            ks.sync_modifiers();
        }
        let r = window.process_window_events(0);
        // HONOUR THE ESCALATION LADDER. Collapsing every non-DoNothing result
        // into `RefreshDom` re-ran the APP's `layout()` callback for a scroll —
        // the heaviest level (5) for an event the engine classified as level
        // 1-2. `common/event.rs` documents the same trap on the autoscroll
        // timer: "Returning RefreshDom re-invoked the APP's layout() callback
        // every 16ms for the entire duration of a drag-autoscroll." Measured on
        // AzWriter: 121-443 ms per scroll frame escalated, ~6 ms honoured.
        //
        // Same split the four desktop backends use — heavy reasons regenerate,
        // light ones only repaint.
        use azul_core::events::ProcessEventResult as PER;
        match r {
            PER::ShouldRegenerateDomCurrentWindow | PER::ShouldRegenerateDomAllWindows => {
                window
                    .common
                    .request_regeneration(RelayoutReason::RefreshDom);
            }
            // NOT a DOM rebuild. The pass has ALREADY re-run layout on the
            // existing StyledDom and refreshed the per-DOM display list — that
            // is what "incremental" means. Calling `regenerate_layout` here
            // would throw that work away and re-invoke the app's
            // `layout_callback`, rebuilding the DOM from application data that
            // has not caught up yet: an IME commit landed in the engine's
            // StyledDom and was then overwritten by the app's unchanged model,
            // so typing composed, committed, and vanished.
            // The pass CLASSIFIED this as incremental; it did not perform it.
            // Somebody has to run `incremental_relayout` on the existing
            // StyledDom and then declare relayout-only so the frame path skips
            // `regenerate_layout`. macOS does exactly this in
            // `apply_incremental_relayout_result`; Android did neither, so a
            // committed IME string was re-laid-out from the app's unchanged
            // model and vanished.
            PER::ShouldIncrementalRelayout => {
                let mut dbg = None;
                if let Err(e) = window.incremental_relayout_dispatching(
                    crate::desktop::shell2::common::event::IncrementalRelayout::Restyle,
                    &mut dbg,
                ) {
                    log_error!(
                        LogCategory::Layout,
                        "[Android] incremental relayout failed: {}",
                        e
                    );
                }
                window.common.request_relayout_only();
                window.needs_rerender = true;
            }
            PER::UpdateHitTesterAndProcessAgain
            | PER::ShouldUpdateDisplayListCurrentWindow
            | PER::ShouldReRenderCurrentWindow => {
                window.needs_rerender = true;
            }
            PER::DoNothing => {}
        }
    }

    // After callbacks have observed any native-gesture override the
    // Android `GestureDetector` JNI bridge injected this frame, clear
    // the slot so a stale OS gesture doesn't keep firing. No-op until
    // #17 wires real injection.
    if let Some(lw) = window.common.layout_window.as_mut() {
        lw.gesture_drag_manager.clear_native_gesture();
    }
}

/// Map the Android `Keycode` enum to Azul's `VirtualKeyCode` for the
/// most common navigation / editing keys. Letters and digits arrive via
/// the soft keyboard's text-input path (Sprint H follow-up — wires
/// `KeyCharacterMap.get` for unicode), so this map only handles the
/// non-character keys that callbacks query through
/// `KeyboardState::is_key_down` / `current_virtual_keycode`.
#[cfg(all(target_os = "android", feature = "android-activity"))]
fn map_keycode(k: Keycode) -> Option<azul_core::window::VirtualKeyCode> {
    use azul_core::window::VirtualKeyCode as V;
    Some(match k {
        Keycode::Enter | Keycode::NumpadEnter => V::Return,
        Keycode::Space => V::Space,
        Keycode::Tab => V::Tab,
        Keycode::Escape => V::Escape,
        Keycode::Del => V::Back,
        Keycode::ForwardDel => V::Delete,
        Keycode::DpadLeft => V::Left,
        Keycode::DpadRight => V::Right,
        Keycode::DpadUp => V::Up,
        Keycode::DpadDown => V::Down,
        Keycode::ShiftLeft => V::LShift,
        Keycode::ShiftRight => V::RShift,
        Keycode::CtrlLeft => V::LControl,
        Keycode::CtrlRight => V::RControl,
        Keycode::AltLeft => V::LAlt,
        Keycode::AltRight => V::RAlt,
        _ => return None,
    })
}

#[cfg(all(
    target_os = "android",
    feature = "android-activity",
    feature = "ndk",
    feature = "cpurender"
))]
fn render_frame(window: &mut AndroidWindow) -> Result<(), WindowError> {
    // Sprint G: pixmap → ANativeWindow_lock → memcpy → unlockAndPost.
    //
    // Caller must arrange for `window.cpu_backend.last_frame` to be populated
    // (typically by a regenerate_layout() invocation). Until that wiring is
    // in place we present whatever pixmap is present, or no-op.
    let nw = match window.native_window.as_ref() {
        Some(nw) => nw,
        None => return Ok(()), // background — surface released
    };

    let pixmap = match window.cpu_backend.last_frame.as_ref() {
        Some(p) => p,
        None => return Ok(()), // nothing to present yet
    };

    let pw = pixmap.width() as i32;
    let ph = pixmap.height() as i32;
    if pw <= 0 || ph <= 0 {
        return Ok(());
    }

    // Tell the surface we want RGBA8 of this exact size. If Android can't
    // satisfy (surface gone, surfaceflinger rejected the format) SKIP the
    // frame: locking anyway hands us a buffer whose format/geometry does not
    // match the bytes we are about to write, and the old `let _ =` swallow
    // then blitted RGBA rows into it regardless.
    if let Err(e) = nw.set_buffers_geometry(
        pw,
        ph,
        Some(ndk::hardware_buffer_format::HardwareBufferFormat::R8G8B8A8_UNORM),
    ) {
        log_debug!(
            LogCategory::Rendering,
            "[Android] setBuffersGeometry({}x{} RGBA8) failed: {}; skipping frame",
            pw,
            ph,
            e,
        );
        return Ok(());
    }

    let mut guard = match nw.lock(None) {
        Ok(g) => g,
        Err(e) => {
            log_debug!(
                LogCategory::Rendering,
                "[Android] ANativeWindow_lock failed: {}",
                e
            );
            return Ok(());
        }
    };

    // The locked buffer's REAL format. `lines()` derives its bytes-per-pixel
    // from this, so a producer that ignored the RGBA8 request (legacy fixed-
    // format surfaces) would make the copy below reinterpret RGBA bytes as
    // 565/etc. — garbage on every pixel. There is no "unlock without post"
    // in the NDK (ANativeWindow_unlockAndPost is the only unlock), so on a
    // mismatch present a deterministic cleared frame instead of the buffer's
    // undefined contents.
    {
        use ndk::hardware_buffer_format::HardwareBufferFormat as Hbf;
        let format = guard.format();
        if !matches!(format, Hbf::R8G8B8A8_UNORM | Hbf::R8G8B8X8_UNORM) {
            log_debug!(
                LogCategory::Rendering,
                "[Android] lock returned non-RGBA8 buffer format {:?}; clearing frame",
                format,
            );
            if let Some(bytes) = guard.bytes() {
                // SAFETY: writing initialised bytes into MaybeUninit is sound.
                unsafe {
                    core::ptr::write_bytes(bytes.as_mut_ptr().cast::<u8>(), 0, bytes.len());
                }
            }
            return Ok(()); // guard drop unlockAndPosts the cleared buffer
        }
    }

    // Per-line blit. `lines()` returns one mutable slice per scanline,
    // trimmed to the visible width — exactly what we need for an RGBA→RGBA
    // copy where stride may exceed width.
    //
    // Any part of the buffer the pixmap does not cover MUST still be written:
    // ANativeWindow_lock hands back a dequeued buffer with UNDEFINED contents
    // (typically a stale frame from several swaps ago — Android does not
    // guarantee back-buffer preservation), so rows/columns we skip would show
    // garbage. Normally geometry matches the pixmap exactly and the fills
    // below are no-ops; they only run if the buffer disagrees with the
    // geometry we just set.
    let src = pixmap.data();
    let src_stride = (pw as usize) * 4;
    let dst_stride = guard.stride() * 4;
    let dst_rows = guard.height().min(ph as usize);

    // WHICH ROWS. Full copy unless we can prove this exact buffer already holds
    // a frame we produced and we know everything that changed since.
    let dpi = window.common.current_window_state().size.dpi as f32 / 96.0;
    let this_frame_rows = window.damage_rows(dpi, ph as usize);
    let buffer_id = guard.bytes().map_or(0usize, |b| b.as_ptr() as usize);
    let rows_to_copy: Option<Vec<(usize, usize)>> = match (
        this_frame_rows.as_ref(),
        window.buffer_frames.get(&buffer_id).copied(),
    ) {
        // Known buffer AND bounded damage: patch only what changed since the
        // frame it holds. Its own frame counts as already-present content.
        (Some(_), Some(seq)) => window.rows_dirty_since(seq),
        // Unseen buffer, or a full-damage frame: the contents are undefined,
        // so every row must be written.
        _ => None,
    };

    let guard_height_for_log = guard.height();
    let Some(dst) = guard.bytes() else {
        return Ok(());
    };
    let dst_ptr = dst.as_mut_ptr().cast::<u8>();
    let dst_len = dst.len();

    // SAFETY (shared by both arms): `dst` is `&mut [MaybeUninit<u8>]` of
    // `dst_len` bytes; every write below is bounds-checked against it and
    // writes initialised bytes. Nothing reads `dst` before writing it.
    let mut copy_row = |y: usize| {
        let dst_off = y * dst_stride;
        if dst_off >= dst_len {
            return;
        }
        let dst_room = (dst_len - dst_off).min(dst_stride);
        let src_off = y * src_stride;
        let n = if src_off < src.len() {
            (src.len() - src_off).min(src_stride).min(dst_room)
        } else {
            0
        };
        unsafe {
            let row = dst_ptr.add(dst_off);
            if n > 0 {
                core::ptr::copy_nonoverlapping(src.as_ptr().add(src_off), row, n);
            }
            if n < dst_room {
                // Beyond the pixmap: the buffer may be wider/taller than the
                // frame and its contents are undefined, so clear rather than
                // leave whatever was there.
                core::ptr::write_bytes(row.add(n), 0, dst_room - n);
            }
        }
    };

    match &rows_to_copy {
        Some(ranges) => {
            for (top, bottom) in ranges {
                for y in *top..(*bottom).min(dst_rows) {
                    copy_row(y);
                }
            }
        }
        None => {
            for y in 0..guard_height_for_log {
                copy_row(y);
            }
        }
    }

    // AZ_DUMP_PRESENT=1 reports whether the partial path is actually engaging.
    // Bookkeeping that always falls back to a full copy is worse than no
    // bookkeeping, and the two are indistinguishable from the rendering.
    #[cfg(feature = "std")]
    if android_debug_flag("AZ_DUMP_PRESENT", "debug.az.present") {
        let (kind, rows) = match &rows_to_copy {
            Some(r) => ("partial", r.iter().map(|(a, b)| b - a).sum::<usize>()),
            None => ("full", guard_height_for_log),
        };
        log_info!(
            LogCategory::Rendering,
            "[Android] present {} — {} of {} rows",
            kind,
            rows,
            guard_height_for_log,
        );
    }

    // Bookkeeping AFTER a successful copy: this buffer now holds this frame,
    // and this frame's damage joins the history for the next rotation.
    window.frame_seq = window.frame_seq.wrapping_add(1);
    let seq = window.frame_seq;
    window.buffer_frames.insert(buffer_id, seq);
    // A full copy makes every row current, so it contributes NO damage to
    // subsequent frames — recording it as "everything dirty" would force the
    // next rotation into a full copy for no reason.
    let recorded = match (&rows_to_copy, this_frame_rows) {
        (None, _) => Vec::new(),
        (Some(_), Some(rows)) => rows,
        (Some(_), None) => Vec::new(),
    };
    window.damage_history.push_back((seq, recorded));
    while window.damage_history.len() > AndroidWindow::DAMAGE_HISTORY {
        window.damage_history.pop_front();
    }
    // Buffer pools are tiny; a map that only ever grows would be a slow leak
    // if a surface were recreated repeatedly.
    if window.buffer_frames.len() > 8 {
        let cutoff = seq.saturating_sub(AndroidWindow::DAMAGE_HISTORY as u64);
        window.buffer_frames.retain(|_, v| *v >= cutoff);
    }

    // guard.drop() calls ANativeWindow_unlockAndPost
    Ok(())
}

