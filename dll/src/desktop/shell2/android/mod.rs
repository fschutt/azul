/// Inject `debug.az.env` into the process environment.
///
/// Format: `KEY=VALUE` pairs separated by `;`. A pair with no `=`, or an empty
/// key, is skipped rather than setting a nonsense variable.
///
/// SAFETY / ORDERING: `std::env::set_var` is not thread-safe. This runs as the
/// first statement of `android_main`, before the window, the JNI publish, any
/// timer or any worker exists, which is the only place that is sound.
#[cfg(target_os = "android")]
fn inject_env_from_property() {
    let Ok(out) = std::process::Command::new("getprop")
        .arg("debug.az.env")
        .output()
    else {
        return;
    };
    let raw = String::from_utf8_lossy(&out.stdout);
    let raw = raw.trim();
    if raw.is_empty() {
        return;
    }
    for pair in raw.split(';') {
        let Some((k, v)) = pair.split_once('=') else {
            continue;
        };
        let (k, v) = (k.trim(), v.trim());
        if k.is_empty() {
            continue;
        }
        log_info!(
            LogCategory::EventLoop,
            "[Android] env from debug.az.env: {}={}",
            k,
            v
        );
        std::env::set_var(k, v);
    }
}

/// A debug knob, from the env or from a `debug.az.*` system property.
///
/// An activity cannot be given an environment variable — `am start` builds an
/// Intent and the process inherits the zygote's environment, not the shell's —
/// so every `AZ_*` knob is unreachable on Android unless it has a property
/// alias. Same mechanism `AZ_E2E` uses (`debug.az.e2e`).
///
///     adb shell setprop debug.az.present 1
#[cfg(target_os = "android")]
pub(crate) fn android_debug_flag(env_name: &str, prop: &str) -> bool {
    if std::env::var_os(env_name).is_some() {
        return true;
    }
    std::process::Command::new("getprop")
        .arg(prop)
        .output()
        .ok()
        .map(|o| {
            let v = String::from_utf8_lossy(&o.stdout);
            let v = v.trim();
            !v.is_empty() && v != "0" && v != "false"
        })
        .unwrap_or(false)
}

/// Ask Android to show or hide the on-screen keyboard.
///
/// Rust -> Java, the opposite direction from every other bridge in this file.
/// `InputMethodManager` is a Java-only API: there is no NDK entry point for it,
/// so raising the keyboard REQUIRES a JNI call out. Until this existed there
/// was no way to bring up a keyboard on Android at all — not a missing caller,
/// a missing capability.
///
/// Best-effort by design: a failure here means the user gets no keyboard, which
/// is bad, but it is not a reason to take the app down mid-layout.
#[cfg(all(target_os = "android", feature = "jni"))]
pub fn set_soft_keyboard_visible(visible: bool) {
    use jni::JavaVM;

    let vm_ptr = java_vm_ptr();
    let activity_ptr = activity_ptr();
    if vm_ptr.is_null() || activity_ptr.is_null() {
        log_debug!(
            LogCategory::Input,
            "[Android] soft keyboard: JNI context not published yet"
        );
        return;
    }
    let result = (|| -> Result<(), String> {
        let vm = unsafe { JavaVM::from_raw(vm_ptr as *mut jni::sys::JavaVM) }
            .map_err(|e| format!("JavaVM::from_raw: {e:?}"))?;
        let mut env = vm
            .attach_current_thread()
            .map_err(|e| format!("attach_current_thread: {e:?}"))?;
        let activity =
            unsafe { jni::objects::JObject::from_raw(activity_ptr as jni::sys::jobject) };
        // Static helper on the Java side rather than open-coding the
        // InputMethodManager dance (getSystemService -> showSoftInput with the
        // right view and flags) through reflection from here.
        // Through the ACTIVITY's class loader: this thread has no Java frame,
        // so a bare `find_class` would resolve against the system loader and
        // never see an APK class. See `extra::find_app_class`.
        let class = crate::desktop::extra::find_app_class(
            &mut env,
            &activity,
            "com/azul/text/NativeTextBridge",
        )
        .ok_or_else(|| "NativeTextBridge not in this APK".to_string())?;
        env.call_static_method(
            &class,
            if visible {
                "showKeyboard"
            } else {
                "hideKeyboard"
            },
            "(Landroid/app/Activity;)V",
            &[jni::objects::JValue::Object(&activity)],
        )
        .map(|_| ())
        .map_err(|e| {
            let _ = env.exception_clear();
            format!("call {}: {e:?}", if visible { "show" } else { "hide" })
        })
    })();
    if let Err(e) = result {
        log_debug!(LogCategory::Input, "[Android] soft keyboard: {e}");
    }
}

