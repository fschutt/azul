/// The `android.view.HapticFeedbackConstants` field name this pattern is
/// rendered as, or `None` if Android has no constant for it.
///
/// `None` is not a failure — it is the signal to walk
/// [`HapticPattern::fallback`] and ask again. The chirp patterns (`Rise`,
/// `Fall`, `Spin`) genuinely have no `performHapticFeedback` constant: they
/// exist only as `VibrationEffect.Composition` primitives, which need the
/// `VIBRATE` permission (see the note on `play_haptic`).
#[cfg(all(target_os = "android", feature = "jni"))]
const fn haptic_constant_name(pattern: azul_core::haptics::HapticPattern) -> Option<&'static str> {
    use azul_core::haptics::HapticPattern::*;
    Some(match pattern {
        Selection => "CLOCK_TICK",
        ImpactLight | ImpactSoft => "KEYBOARD_TAP",
        ImpactMedium => "VIRTUAL_KEY",
        ImpactHeavy | ImpactRigid => "LONG_PRESS",
        Success => "CONFIRM",
        Error => "REJECT",
        KeyPress => "KEYBOARD_PRESS",
        KeyRelease => "KEYBOARD_RELEASE",
        LongPress => "LONG_PRESS",
        ContextClick => "CONTEXT_CLICK",
        TextHandleMove => "TEXT_HANDLE_MOVE",
        GestureStart => "GESTURE_START",
        GestureEnd => "GESTURE_END",
        // No constant: degrade via the fallback chain.
        Warning | Rise | Fall | Spin => return None,
    })
}

/// Play one haptic request through the decor view's `performHapticFeedback`.
///
/// # Why `performHapticFeedback` and not `Vibrator`/`VibrationEffect`
///
/// `Vibrator` is the richer API — it is the only way to reach the composition
/// primitives, amplitude scaling and arbitrary waveforms — but it requires the
/// `android.permission.VIBRATE` manifest entry, which is the APP's decision
/// and not something a UI toolkit can declare on its behalf. An app that has
/// not declared it gets a `SecurityException`, not a silent no-op.
/// `performHapticFeedback` needs no permission, and it respects the user's
/// system-wide "touch feedback" setting, which the `Vibrator` path bypasses.
///
/// So `HapticRequest::intensity` and `duration_ms` are IGNORED here: this API
/// has neither axis. Wiring the `Vibrator` path is logged as 9g-i-a rather
/// than guessed at, because it needs a permission decision from the app.
///
/// # Why the constants are looked up reflectively
///
/// `HapticFeedbackConstants` gained values over many API levels (`CONFIRM` and
/// `REJECT` in 30, `GESTURE_START`/`GESTURE_END` in 30, `TEXT_HANDLE_MOVE` in
/// 27). Hard-coding the ints would fire a WRONG effect on an older device
/// rather than none, because the framework happily accepts an unknown int and
/// picks something. Reading the field by name means an absent constant raises
/// `NoSuchFieldError`, which is caught and degraded through
/// [`HapticPattern::fallback`] to something the device does have.
/// The `VibrationEffect.Composition` primitive for this pattern, by NAME.
///
/// `None` means the pattern has no composition primitive and belongs on the
/// `performHapticFeedback` path instead.
///
/// Named rather than numbered for the same reason `haptic_constant_name` is:
/// the primitives arrived across API levels (SPIN and the chirps in 31), and a
/// hard-coded int fires the WRONG effect on a device that predates it, because
/// the framework accepts an unknown id and picks something.
#[cfg(all(target_os = "android", feature = "jni"))]
const fn composition_primitive_name(
    pattern: azul_core::haptics::HapticPattern,
) -> Option<&'static str> {
    use azul_core::haptics::HapticPattern::*;
    Some(match pattern {
        ImpactLight | ImpactSoft => "PRIMITIVE_LOW_TICK",
        ImpactMedium => "PRIMITIVE_TICK",
        ImpactHeavy | ImpactRigid => "PRIMITIVE_CLICK",
        Rise => "PRIMITIVE_QUICK_RISE",
        Fall => "PRIMITIVE_QUICK_FALL",
        Spin => "PRIMITIVE_SPIN",
        // Everything else is better served by performHapticFeedback, which
        // respects the user's touch-feedback setting.
        _ => return None,
    })
}

/// Play through `Vibrator`/`VibrationEffect.Composition`.
///
/// # Why this exists next to `performHapticFeedback`
///
/// `performHapticFeedback` needs no permission and honours the user's
/// touch-feedback setting, which is why it stays the default. What it CANNOT
/// do is scale intensity or reach the chirp primitives - there is no
/// `HapticFeedbackConstants` for a rise, a fall or a spin, and no way to ask
/// for a half-strength tap. Those are the only cases routed here.
///
/// # The permission
///
/// `Vibrator.vibrate` requires `android.permission.VIBRATE`. Azul's own
/// manifest (`scripts/android/AndroidManifest.xml`) declares it, so an app
/// built from that template is fine - but an app supplying its OWN manifest
/// may not, and Android answers that with a `SecurityException` rather than a
/// silent no-op. Every call here is therefore fallible and the exception is
/// CLEARED: a pending JNI exception aborts the process at the next boundary,
/// which would turn a missing permission into a crash far from its cause.
///
/// Returns whether the effect was actually played, so the caller can fall back.
#[cfg(all(target_os = "android", feature = "jni"))]
fn play_via_vibrator(
    env: &mut jni::JNIEnv,
    activity: &jni::objects::JObject,
    request: &azul_core::haptics::HapticRequest,
) -> bool {
    use jni::objects::{JObject, JValue};

    let Some(primitive_name) = composition_primitive_name(request.pattern) else {
        return false;
    };

    let mut attempt = || -> Result<bool, String> {
        // The composition API is API 30+; its absence is the common case on
        // older devices and must degrade, not error.
        let composition_cls = match env.find_class("android/os/VibrationEffect$Composition") {
            Ok(c) => c,
            Err(_) => {
                let _ = env.exception_clear();
                return Ok(false);
            }
        };
        let primitive = match env
            .get_static_field(&composition_cls, primitive_name, "I")
            .and_then(|v| v.i())
        {
            Ok(v) => v,
            Err(_) => {
                // This API level predates the primitive (SPIN and the chirps
                // are 31+). Fall back rather than fire a wrong id.
                let _ = env.exception_clear();
                return Ok(false);
            }
        };

        // The vibrator itself. API 31 moved it behind VibratorManager; the
        // older direct service still works below that, so both are tried.
        let vibrator: JObject = {
            let manager = env
                .call_method(
                    activity,
                    "getSystemService",
                    "(Ljava/lang/String;)Ljava/lang/Object;",
                    &[JValue::Object(&JObject::from(
                        env.new_string("vibrator_manager")
                            .map_err(|e| format!("new_string: {e:?}"))?,
                    ))],
                )
                .and_then(|v| v.l());
            match manager {
                Ok(m) if !m.is_null() => env
                    .call_method(&m, "getDefaultVibrator", "()Landroid/os/Vibrator;", &[])
                    .and_then(|v| v.l())
                    .map_err(|e| {
                        let _ = env.exception_clear();
                        format!("getDefaultVibrator: {e:?}")
                    })?,
                _ => {
                    let _ = env.exception_clear();
                    env.call_method(
                        activity,
                        "getSystemService",
                        "(Ljava/lang/String;)Ljava/lang/Object;",
                        &[JValue::Object(&JObject::from(
                            env.new_string("vibrator")
                                .map_err(|e| format!("new_string: {e:?}"))?,
                        ))],
                    )
                    .and_then(|v| v.l())
                    .map_err(|e| {
                        let _ = env.exception_clear();
                        format!("getSystemService(vibrator): {e:?}")
                    })?
                }
            }
        };
        if vibrator.is_null() {
            return Ok(false);
        }
        // A device with no actuator: asking it to vibrate is not an error, it
        // just does nothing, and falling back to performHapticFeedback there
        // is pointless too.
        let has = env
            .call_method(&vibrator, "hasVibrator", "()Z", &[])
            .and_then(|v| v.z())
            .unwrap_or(false);
        if !has {
            return Ok(true);
        }

        // startComposition().addPrimitive(id, scale).compose()
        let composition = env
            .call_static_method(
                "android/os/VibrationEffect",
                "startComposition",
                "()Landroid/os/VibrationEffect$Composition;",
                &[],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("startComposition: {e:?}")
            })?;
        // THE POINT OF THIS PATH: a real scale, which
        // `performHapticFeedback` has no way to express.
        let scale = request.intensity_clamped();
        let composition = env
            .call_method(
                &composition,
                "addPrimitive",
                "(IF)Landroid/os/VibrationEffect$Composition;",
                &[JValue::Int(primitive), JValue::Float(scale)],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("addPrimitive: {e:?}")
            })?;
        let effect = env
            .call_method(
                &composition,
                "compose",
                "()Landroid/os/VibrationEffect;",
                &[],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("compose: {e:?}")
            })?;

        env.call_method(
            &vibrator,
            "vibrate",
            "(Landroid/os/VibrationEffect;)V",
            &[JValue::Object(&effect)],
        )
        .map(|_| true)
        .map_err(|e| {
            // A missing VIBRATE permission lands HERE as a SecurityException.
            // Clearing it is what keeps a permission problem from aborting the
            // process at the next JNI boundary.
            let _ = env.exception_clear();
            format!("vibrate: {e:?} (is android.permission.VIBRATE declared?)")
        })
    };

    match attempt() {
        Ok(played) => played,
        Err(e) => {
            log_debug!(LogCategory::Input, "[Android] vibrator: {e}");
            false
        }
    }
}

/// Rumble ONE CONTROLLER's motor (9g-i-d-a).
///
/// Android reaches a pad's actuator through the same `Vibrator` interface as
/// the phone's own - a different device, one API - which is why this lives
/// beside `play_via_vibrator` rather than in the gamepad backend. The gilrs
/// path the desktop uses does not exist here.
///
/// `pad` is the Android INPUT DEVICE ID, which is exactly what
/// `gamepad::android` publishes as the `GamepadId`, so no mapping table is
/// needed - and a stale id from a pad that has since unplugged simply yields
/// a null device.
///
/// # Not the composition API
///
/// `play_via_vibrator` above builds a composition PRIMITIVE, which is a tap.
/// A rumble is a sustained buzz of a given strength, which is
/// `createOneShot(ms, amplitude)` - and that call is API 26, so unlike the
/// primitives it needs no version fallback.
/// `AXIS_SCROLL` units to RADIANS for one rotary device (9c-i-a).
///
/// # Where the constant comes from
///
/// `InputDevice.MotionRange.getResolution()` is documented as "the number of
/// units per millimeter, or per RADIAN for rotational axes", and `AXIS_SCROLL`
/// on a `SOURCE_ROTARY_ENCODER` is a rotational axis. So the conversion is the
/// DEVICE's own, not a constant invented here - which is what makes it right on
/// watches nobody in this project owns, where crowns differ by detent count and
/// gearing.
///
/// It is not in the rotary-input guide, which is why this was logged as
/// "Android does not document it": the guide talks about `getScaledScrollFactor`
/// (units to PIXELS, for scrolling) and never mentions the angular one.
///
/// # Zero means unknown, and unknown means 0.0
///
/// `getResolution` returns 0 when the driver did not report one, and a great
/// many devices do not. Dividing by it would give an infinity; guessing a
/// substitute would put a fabricated angle in a field whose whole value is
/// being trustworthy. `0.0` continues to say "this platform did not measure
/// that", exactly as before - it is now the fallback rather than the rule.
///
/// Cached per device: the resolution is a property of the hardware, and a JNI
/// round trip per sample at crown-spin rates would cost more than the value.
#[cfg(all(target_os = "android", feature = "jni"))]
fn rotary_scroll_to_radians(device_id: i32, scroll: f32) -> f32 {
    azul_layout::managers::gesture::rotary_units_to_radians(scroll, rotary_resolution(device_id))
}

/// Without `jni` there is no way to ask the device, so the honest answer is
/// the one this had before.
#[cfg(all(target_os = "android", not(feature = "jni")))]
fn rotary_scroll_to_radians(_device_id: i32, _scroll: f32) -> f32 {
    0.0
}

/// `InputDevice.getDevice(id).getMotionRange(AXIS_SCROLL, SOURCE_ROTARY_ENCODER)
/// .getResolution()`, cached. `0.0` when unknown.
#[cfg(all(target_os = "android", feature = "jni"))]
fn rotary_resolution(device_id: i32) -> f32 {
    use jni::{objects::JValue, JavaVM};

    static CACHE: std::sync::Mutex<Option<std::collections::BTreeMap<i32, f32>>> =
        std::sync::Mutex::new(None);
    if let Ok(guard) = CACHE.lock() {
        if let Some(hit) = guard.as_ref().and_then(|m| m.get(&device_id)) {
            return *hit;
        }
    }

    /// `MotionEvent.AXIS_SCROLL`.
    const AXIS_SCROLL: i32 = 26;
    /// `InputDevice.SOURCE_ROTARY_ENCODER`.
    const SOURCE_ROTARY_ENCODER: i32 = 0x0040_0000;

    let vm_ptr = java_vm_ptr();
    if vm_ptr.is_null() {
        return 0.0;
    }
    let resolved = (|| -> Result<f32, String> {
        let vm = unsafe { JavaVM::from_raw(vm_ptr as *mut jni::sys::JavaVM) }
            .map_err(|e| format!("JavaVM::from_raw: {e:?}"))?;
        let mut env = vm
            .attach_current_thread()
            .map_err(|e| format!("attach_current_thread: {e:?}"))?;
        // `android.view.InputDevice` is on the BOOT classpath, so a bare
        // `find_class` resolves it from a Rust thread with no Java frame.
        let device = env
            .call_static_method(
                "android/view/InputDevice",
                "getDevice",
                "(I)Landroid/view/InputDevice;",
                &[JValue::Int(device_id)],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("getDevice({device_id}): {e:?}")
            })?;
        if device.is_null() {
            return Ok(0.0);
        }
        // THE SOURCE-QUALIFIED overload, not `getMotionRange(int)`: a device
        // can report the same axis on several sources, and the unqualified
        // form answers for whichever the platform picks - which on a watch
        // that also has a touchscreen is not the crown.
        let range = env
            .call_method(
                &device,
                "getMotionRange",
                "(II)Landroid/view/InputDevice$MotionRange;",
                &[JValue::Int(AXIS_SCROLL), JValue::Int(SOURCE_ROTARY_ENCODER)],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("getMotionRange: {e:?}")
            })?;
        if range.is_null() {
            return Ok(0.0);
        }
        env.call_method(&range, "getResolution", "()F", &[])
            .and_then(|v| v.f())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("getResolution: {e:?}")
            })
    })();

    let value = match resolved {
        Ok(v) if v.is_finite() && v > 0.0 => v,
        Ok(_) => 0.0,
        Err(e) => {
            log_debug!(LogCategory::Input, "[Android] rotary resolution: {e}");
            0.0
        }
    };
    if let Ok(mut guard) = CACHE.lock() {
        guard.get_or_insert_with(Default::default).insert(device_id, value);
    }
    value
}

#[cfg(all(target_os = "android", feature = "jni"))]
fn play_gamepad_rumble(
    env: &mut jni::JNIEnv,
    request: &azul_core::haptics::HapticRequest,
    pad: u32,
) -> bool {
    use jni::objects::{JObject, JValue};

    // Zero intensity is "do not play", NOT amplitude 0 - Android rejects that
    // as invalid rather than treating it as silence.
    if request.intensity_clamped() <= 0.0 {
        return false;
    }

    let mut attempt = || -> Result<bool, String> {
        // `android.view.InputDevice` is on the BOOT classpath, so a bare
        // `find_class` resolves it from a Rust thread - the same reason
        // `HapticFeedbackConstants` does not need `find_app_class`.
        let device = env
            .call_static_method(
                "android/view/InputDevice",
                "getDevice",
                "(I)Landroid/view/InputDevice;",
                &[JValue::Int(pad as i32)],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("InputDevice.getDevice({pad}): {e:?}")
            })?;
        if device.is_null() {
            // The pad unplugged between the callback and this drain. Normal.
            return Ok(false);
        }

        // API 31 moved a device's actuators behind `VibratorManager`; the
        // older `getVibrator()` still answers below that. Same two-step the
        // phone's own vibrator lookup makes, and for the same reason.
        let vibrator: JObject = {
            let manager = env
                .call_method(
                    &device,
                    "getVibratorManager",
                    "()Landroid/os/VibratorManager;",
                    &[],
                )
                .and_then(|v| v.l());
            match manager {
                Ok(m) if !m.is_null() => env
                    .call_method(&m, "getDefaultVibrator", "()Landroid/os/Vibrator;", &[])
                    .and_then(|v| v.l())
                    .map_err(|e| {
                        let _ = env.exception_clear();
                        format!("pad getDefaultVibrator: {e:?}")
                    })?,
                _ => {
                    let _ = env.exception_clear();
                    env.call_method(&device, "getVibrator", "()Landroid/os/Vibrator;", &[])
                        .and_then(|v| v.l())
                        .map_err(|e| {
                            let _ = env.exception_clear();
                            format!("InputDevice.getVibrator: {e:?}")
                        })?
                }
            }
        };
        if vibrator.is_null() {
            return Ok(false);
        }
        // MOST CONTROLLERS HAVE NO MOTOR, and `getVibrator` still hands back a
        // non-null stub for them. `hasVibrator` is the real test; without it
        // every rumble would look like it worked.
        let has = env
            .call_method(&vibrator, "hasVibrator", "()Z", &[])
            .and_then(|v| v.z())
            .unwrap_or(false);
        if !has {
            return Ok(false);
        }

        // `createOneShot(long, int)` - a sustained buzz, not a tap. Amplitude
        // is 1..=255 and 0 THROWS, which is what `amplitude_u8` floors.
        let effect = env
            .call_static_method(
                "android/os/VibrationEffect",
                "createOneShot",
                "(JI)Landroid/os/VibrationEffect;",
                &[
                    JValue::Long(i64::from(request.rumble_duration_ms())),
                    JValue::Int(i32::from(request.amplitude_u8())),
                ],
            )
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("createOneShot: {e:?}")
            })?;

        env.call_method(
            &vibrator,
            "vibrate",
            "(Landroid/os/VibrationEffect;)V",
            &[JValue::Object(&effect)],
        )
        .map(|_| true)
        .map_err(|e| {
            // A missing VIBRATE permission arrives here as a SecurityException;
            // clearing it is what stops a permission problem from aborting the
            // process at the next JNI boundary.
            let _ = env.exception_clear();
            format!("pad vibrate: {e:?} (is android.permission.VIBRATE declared?)")
        })
    };

    match attempt() {
        Ok(played) => played,
        Err(e) => {
            log_debug!(LogCategory::Input, "[Android] pad rumble: {e}");
            false
        }
    }
}

#[cfg(all(target_os = "android", feature = "jni"))]
pub fn play_haptic(request: &azul_core::haptics::HapticRequest) {
    use azul_core::haptics::HapticTarget;
    use jni::JavaVM;

    // The phone body is not a stand-in for a gamepad's motors, and a Pen has
    // no actuator on any Android device - so only these two targets play.
    let pad = match request.target {
        HapticTarget::System => None,
        // 9g-i-d-a: the pad's own motor, reached through `InputDevice`.
        HapticTarget::Gamepad(pad) => Some(pad),
        _ => return,
    };

    let vm_ptr = java_vm_ptr();
    let activity_ptr = activity_ptr();
    if vm_ptr.is_null() || activity_ptr.is_null() {
        return;
    }

    let result = (|| -> Result<(), String> {
        let vm = unsafe { JavaVM::from_raw(vm_ptr as *mut jni::sys::JavaVM) }
            .map_err(|e| format!("JavaVM::from_raw: {e:?}"))?;
        let mut env = vm
            .attach_current_thread()
            .map_err(|e| format!("attach_current_thread: {e:?}"))?;
        let activity =
            unsafe { jni::objects::JObject::from_raw(activity_ptr as jni::sys::jobject) };

        // A GAMEPAD is a different device entirely: its motor is reached
        // through `InputDevice`, and `performHapticFeedback` below would
        // buzz the PHONE instead - which is the wrong body.
        if let Some(pad) = pad {
            play_gamepad_rumble(&mut env, request, pad);
            return Ok(());
        }

        // THE VIBRATOR PATH FIRST, but only for the two things
        // `performHapticFeedback` cannot express: a scaled intensity, and the
        // chirp primitives (rise / fall / spin) that have no
        // `HapticFeedbackConstants` at all.
        //
        // Everything else deliberately stays on `performHapticFeedback`, which
        // needs no permission and HONOURS THE USER'S touch-feedback setting -
        // the `Vibrator` path bypasses that setting, so routing ordinary taps
        // through it would make an app ignore "turn off haptics".
        let wants_scaling = (request.intensity_clamped() - 1.0).abs() > f32::EPSILON;
        let has_no_constant = haptic_constant_name(request.pattern).is_none();
        if (wants_scaling || has_no_constant) && play_via_vibrator(&mut env, &activity, request) {
            return Ok(());
        }

        // `android.view.*` is on the BOOT classpath, so a bare `find_class`
        // resolves it even from a Rust thread with no Java frame. This is the
        // one case where `find_app_class` is NOT needed — that helper exists
        // for APK classes, which the system loader cannot see.
        let constants = env
            .find_class("android/view/HapticFeedbackConstants")
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("HapticFeedbackConstants: {e:?}")
            })?;

        // Walk the degradation chain until a constant exists on THIS device.
        let mut current = Some(request.pattern);
        let mut effect = None;
        while let Some(pattern) = current {
            if let Some(name) = haptic_constant_name(pattern) {
                match env.get_static_field(&constants, name, "I").and_then(|v| v.i()) {
                    Ok(value) => {
                        effect = Some(value);
                        break;
                    }
                    Err(_) => {
                        // NoSuchFieldError: this API level predates the
                        // constant. Clear it or the pending exception aborts
                        // the process at the next JNI boundary.
                        let _ = env.exception_clear();
                    }
                }
            }
            current = pattern.fallback();
        }
        let Some(effect) = effect else {
            return Err(format!("no constant for {:?} or any fallback", request.pattern));
        };

        let window = env
            .call_method(&activity, "getWindow", "()Landroid/view/Window;", &[])
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("getWindow: {e:?}")
            })?;
        let view = env
            .call_method(&window, "getDecorView", "()Landroid/view/View;", &[])
            .and_then(|v| v.l())
            .map_err(|e| {
                let _ = env.exception_clear();
                format!("getDecorView: {e:?}")
            })?;

        // The one-argument form, deliberately: the two-argument overload takes
        // flags that OVERRIDE the user's system haptics setting, and an app
        // silently ignoring "turn off touch feedback" is a bug, not a feature.
        env.call_method(
            &view,
            "performHapticFeedback",
            "(I)Z",
            &[jni::objects::JValue::Int(effect)],
        )
        .map(|_| ())
        .map_err(|e| {
            let _ = env.exception_clear();
            format!("performHapticFeedback: {e:?}")
        })
    })();

    if let Err(e) = result {
        log_debug!(LogCategory::Input, "[Android] haptic: {e}");
    }
}

