//! Emits the `go.mod` / `go.sum` manifests for the generated Go bindings.
//!
//! The package has exactly one third-party dependency,
//! `github.com/ebitengine/purego` (runtime symbol binding and callback
//! trampolines without cgo), pinned here together with the checksums the
//! Go tool expects in `go.sum` — so `go vet` / `go build` inside the
//! package work offline once the module is in the local cache, and a
//! consumer's `go mod tidy` picks the same version.
//!
//! The module path follows the convention used by other azul language
//! bindings published under `azul.rs/`. Consumers who fork or vendor the
//! package can rewrite the `module` line to match their import structure.

/// The purego release the bindings are generated against.
///
/// v0.10.2 is the newest purego whose `go.mod` still declares `go 1.18`,
/// which is what the bindings need (generics) and what the hello-world
/// guide promises. v0.11.0 raised purego's directive to `go 1.25.0`; a
/// consumer module on any older toolchain could then no longer build. The
/// API surface this generator uses (`RegisterLibFunc`, `NewCallback`,
/// `Dlopen` on dlopen platforms) is identical in every release since v0.7.
pub const PUREGO_VERSION: &str = "v0.10.2";

/// `go.sum` checksum of the purego module zip.
const PUREGO_SUM: &str = "h1:W809HbnvzAxgdm+aOvlSekrM16wGCdT/e76+9tS7gzE=";

/// `go.sum` checksum of purego's `go.mod`.
const PUREGO_GOMOD_SUM: &str = "h1:iIjxzd6CiRiOG0UyXP+V1+jWqUXVjPKLAI0mRfJZTmQ=";

/// Generate the contents of the package's `go.mod`.
///
/// `go 1.21`: the first release with a `go` directive semantics that
/// guarantees toolchain forward-compatibility handling, and the oldest
/// version the CI matrix exercises. Older Go (>= 1.18) compiles the
/// bindings just fine; bumping the directive only blocks people on truly
/// old toolchains.
pub fn generate_go_mod() -> String {
    format!(
        "// go.mod - auto-generated by azul-doc codegen v2 (lang_go).\n\
         // DO NOT EDIT MANUALLY - re-run the generator instead.\n\
         //\n\
         // Consumers who fork or vendor this package can rewrite the\n\
         // `module` line to match their own import path.\n\
         \n\
         module azul.rs/ui/go\n\
         \n\
         go 1.21\n\
         \n\
         require github.com/ebitengine/purego {}\n",
        PUREGO_VERSION
    )
}

/// Generate the contents of the package's `go.sum` (the purego pin's
/// checksums; purego itself has no dependencies).
pub fn generate_go_sum() -> String {
    format!(
        "github.com/ebitengine/purego {v} {sum}\n\
         github.com/ebitengine/purego {v}/go.mod {modsum}\n",
        v = PUREGO_VERSION,
        sum = PUREGO_SUM,
        modsum = PUREGO_GOMOD_SUM
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn go_mod_pins_purego_and_names_the_module() {
        let m = generate_go_mod();
        assert!(m.contains("module azul.rs/ui/go\n"));
        assert!(m.contains(&format!("require github.com/ebitengine/purego {}\n", PUREGO_VERSION)));
        assert!(!m.contains("cgo"));
    }

    #[test]
    fn go_sum_covers_the_pinned_version() {
        let s = generate_go_sum();
        assert_eq!(s.lines().count(), 2);
        assert!(s.starts_with(&format!("github.com/ebitengine/purego {} h1:", PUREGO_VERSION)));
        assert!(s.contains(&format!("{}/go.mod h1:", PUREGO_VERSION)));
    }
}
