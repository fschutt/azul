//! Emits the Dune build manifest for the generated OCaml bindings.
//!
//! Two files are produced:
//!
//! - `dune-project` — declares the Dune lang version. Every Dune workspace needs exactly one of
//!   these at its root.
//! - `dune` — the per-directory build description. We declare a library `azul` that compiles the
//!   generated `azul.ml` / `azul.mli` against `ctypes` and `ctypes-foreign` and links against the
//!   prebuilt native library at runtime via `Dl.dlopen`.
//!
//! The user is expected to drop the platform-appropriate native
//! binary (`libazul.so` / `libazul.dylib` / `azul.dll`) somewhere
//! discoverable by `dlopen` (typically the working directory or
//! `LD_LIBRARY_PATH` / `DYLD_LIBRARY_PATH`). We don't link the
//! native at OCaml link-time because Ctypes-Foreign is a libffi
//! consumer — the binding is loaded dynamically.

/// Single deterministic `dune-project` string.
pub fn generate_dune_project() -> String {
    // Dune 3.x requires `(lang dune ...)` to be the very first
    // non-blank line — comments before it are rejected with
    //   "Invalid first line, expected: (lang <lang> <version>)".
    // Header comments live below the lang stanza.
    let s = r#"(lang dune 3.0)
(name azul)
; ============================================================================
; Auto-generated Dune project file for the Azul GUI framework OCaml bindings.
; Generated by azul-doc codegen v2 (lang_ocaml/dune). DO NOT EDIT MANUALLY.
; ============================================================================
"#;
    s.to_string()
}

/// Single deterministic per-library `dune` file.
///
/// We include `(public_name azul)` because we now generate `azul.opam`.

pub fn generate_dune() -> String {
    let s = r#"; ============================================================================
; Auto-generated Dune build manifest for the Azul OCaml bindings library.
; Generated by azul-doc codegen v2 (lang_ocaml/dune). DO NOT EDIT MANUALLY.
;
; Build with:
;     dune build
;
; The native libazul.so / libazul.dylib / azul.dll must be discoverable by
; dlopen at runtime (e.g. in LD_LIBRARY_PATH, DYLD_LIBRARY_PATH, or the
; current working directory).
; ============================================================================

; The generated azul bindings defined as a local library: `azul.ml` is the
; facade consumers open, `azul_*.ml` the per-module units it includes (one
; per api.json module, one per dependency slice for the types). dune wraps
; the library, so only `Azul` is visible from outside.
; The codegen emits many declarations that are unused by any given consumer;
; that's fine for an FFI-binding library. Suppress warning 32 (unused
; value declaration) so the build doesn't fail on a stable, complete API.
(library
 (name azul)
 (public_name azul)
 (flags (:standard -w -32-26-27-33-34-35-37-39))
 (libraries ctypes ctypes-foreign)
 (modules :standard))

; Build the hello-world example:
(executable
 (name hello_world)
 (modules hello_world)
 (libraries ctypes ctypes-foreign azul))
"#;
    s.to_string()
}

/// Single deterministic `azul.opam` file.
pub fn generate_opam(version: &str) -> String {
    format!(r#"# This file is generated by azul-doc codegen v2. DO NOT EDIT.
opam-version: "2.0"
name: "azul"
version: "{}"
synopsis: "OCaml bindings for the Azul GUI framework"
description: "A free, functional, immediate-mode GUI framework for rapid development of desktop applications written in Rust, supported by a cross-language API."
maintainer: "Felix Schütt"
authors: "Felix Schütt"
license: "MIT"
homepage: "https://azul.rs"
bug-reports: "https://github.com/fschutt/azul/issues"
depends: [
  "ocaml" {{>= "4.14.0"}}
  "dune" {{>= "3.0.0"}}
  "ctypes" {{>= "0.20.0"}}
  "ctypes-foreign"
]
build: [
  ["dune" "subst"] {{dev}}
  [
    "dune"
    "build"
    "-p"
    name
    "-j"
    jobs
    "@install"
    "@runtest" {{with-test}}
    "@doc" {{with-doc}}
  ]
]
"#, version)
}

pub fn generate_hello_world() -> String {
    let s = r#"type my_data_model = { mutable counter : int }

let layout (m : my_data_model) : Azul.Dom.t =
  let label =
    Azul.Dom.p ~css:"font-size: 32px; margin: 0;" (Int.to_string m.counter)
  in
  let button =
    Azul.Button.create "Increase counter"
      ~button_type:Azul.ButtonType.Primary
      ~on_click:(fun () ->
          m.counter <- m.counter + 1;
          Azul.Update.RefreshDom)
  in
  Azul.Dom.body ~children:[ label; button ]

let () =
  let model = { counter = 5 } in
  let window = Azul.WindowCreateOptions.create ~layout () in
  let app_config = Azul.AppConfig.create () in
  let app = Azul.App.create ~model ~app_config () in

  Azul.App.run app window
"#;
    s.to_string()
}
