//! The build manifests of the generated OCaml project.
//!
//! `target/codegen/ocaml/` is a complete dune project — exactly what the
//! release tarball ships and what the hello-world guide describes:
//!
//! - `dune-project` — the workspace root marker (`(lang dune 3.0)`).
//! - `dune` — one library `azul` over every generated unit, and the `hello_world` executable.
//! - `azul.opam` — the package definition `opam install . --deps-only` reads to install `ctypes`,
//!   `ctypes-foreign` and `dune`. It is emitted by [`super::generate`] (as the file section
//!   `azul.opam`), so the manifest never names an installable package that does not exist.
//! - `hello_world.ml` — the guide's counter example, [`hello_world`], included at compile time
//!   from `examples/ocaml/hello_world.ml` (the single source of truth; the guide's code block is
//!   checked against that file).
//!
//! `examples/ocaml/` carries byte-identical copies of `dune` and
//! `dune-project` so the example directory builds the same way after the
//! generated units are copied in (see `scripts/e2e_language_matrix.sh`).
//!
//! The native `libazul.so` / `libazul.dylib` / `azul.dll` is NOT linked at
//! OCaml link time: `azul_loader.ml` `Dl.dlopen`s it at startup (search
//! order: `AZ_DYLIB`, then the platform names in the working directory and
//! the loader path).

/// `dune-project`. Dune 3.x requires `(lang dune ...)` to be the very first
/// line — no comments before it.
pub fn generate_dune_project() -> String {
    "(lang dune 3.0)\n(name azul)\n".to_string()
}

/// `dune`: the library over every generated unit plus the hello-world
/// executable. The library excludes `hello_world` explicitly — with
/// `(modules :standard)` dune reports the module as used by two stanzas.
/// No `(public_name ...)`: the project is consumed in place (the guide's
/// `dune exec ./hello_world.exe`), not installed into the opam switch.
pub fn generate_dune() -> String {
    let s = r#"; ============================================================================
; Dune build manifest for the Azul OCaml bindings.
; Generated by azul-doc codegen v2 (lang_ocaml/dune). DO NOT EDIT MANUALLY.
;
;     opam install . --deps-only     ; ctypes, ctypes-foreign, dune (azul.opam)
;     dune exec ./hello_world.exe    ; libazul.{so,dylib} / azul.dll next to it
; ============================================================================

; The generated bindings as one wrapped library: `azul.ml` is the facade
; consumers open, `azul_*.ml` the per-module units it includes. The codegen
; emits many declarations no single consumer uses; silence the unused-value
; family of warnings for this stable, complete API.
(library
 (name azul)
 (flags (:standard -w -32-26-27-33-34-35-37-39))
 (libraries ctypes ctypes-foreign)
 (modules (:standard \ hello_world)))

(executable
 (name hello_world)
 (modules hello_world)
 (libraries ctypes ctypes-foreign azul))
"#;
    s.to_string()
}

/// `azul.opam`: the dependency manifest for `opam install . --deps-only`.
/// `version` is the api.json version the bindings were generated from.
pub fn generate_opam(version: &str) -> String {
    format!(
        r#"# Generated by azul-doc codegen v2 (lang_ocaml/dune). DO NOT EDIT MANUALLY.
opam-version: "2.0"
name: "azul"
version: "{}"
synopsis: "OCaml bindings for the Azul GUI framework"
description: "A free, functional, immediate-mode GUI framework for rapid development of desktop applications written in Rust, supported by a cross-language API."
maintainer: "Felix Schütt"
authors: "Felix Schütt"
license: "MIT"
homepage: "https://azul.rs"
bug-reports: "https://github.com/fschutt/azul/issues"
depends: [
  "ocaml" {{>= "4.14.0"}}
  "dune" {{>= "3.0.0"}}
  "ctypes" {{>= "0.20.0"}}
  "ctypes-foreign"
]
build: [
  ["dune" "build" "-p" name "-j" jobs]
]
"#,
        version
    )
}

/// The hello-world counter example, verbatim from `examples/ocaml/`.
pub fn hello_world() -> &'static str {
    include_str!("../../../../../examples/ocaml/hello_world.ml")
}
