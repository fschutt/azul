//! Static binding Rust generator
//!
//! Generates standalone Rust code with native function implementations.
//! This is used when statically linking the Azul library into your application.
//!
//! The generated code does NOT depend on the C-API. Instead, functions have
//! real implementations that call directly into the internal azul_core types
//! using transmute for ABI compatibility.
//!
//! Output: `target/codegen/rust-binding-static.rs`
//! Usage: `include!("rust-binding-static.rs")` with `feature = "static"`

use anyhow::Result;

use crate::codegen::v2::config::*;
use crate::codegen::v2::generator::{CodeBuilder, LanguageGenerator};
use crate::codegen::v2::ir::*;

use super::shared;
use crate::codegen::v2::transmute_helpers::{generate_transmuted_fn_body, parse_arg_type};

// ============================================================================
// Static Binding Generator
// ============================================================================

pub struct RustStaticGenerator;

impl LanguageGenerator for RustStaticGenerator {
    fn generate(&self, ir: &CodegenIR, config: &CodegenConfig) -> Result<String> {
        let mut builder = CodeBuilder::new(&config.indent);

        // File header
        builder.line("// Auto-generated by azul-doc codegen v2 (static binding)");
        builder.line("// DO NOT EDIT MANUALLY");
        builder.line("//");
        builder.line("// This file contains the static Rust API with native implementations.");
        builder.line("// Functions call directly into azul_core types using transmute.");
        builder.blank();

        // Generate module structure: pub mod __dll_api_inner { pub mod dll { ... } }
        builder.line("pub mod __dll_api_inner {");
        builder.indent();
        // Lints that a UNIFORM EMITTER cannot avoid, suppressed at the
        // generated module so that real warnings in this file stay visible.
        // azul-dll produced 32705 warnings before this; GitHub truncates the
        // build-log step at that volume, which hides whatever else the step had
        // to say — including genuine errors.
        //
        // Each of these is an artifact of generating one shape for every type,
        // not of anything the author of api.json did wrong:
        //
        //   trivial_casts / trivial_numeric_casts (8038) — the accessor shape is
        //     `&*(self as *const AzX as *const <real path>)`, which is only a
        //     no-op for the subset of types where the wrapper and the real type
        //     coincide. The emitter cannot know which those are per-type, and
        //     writing two shapes to dodge a style lint would make the generator
        //     harder to reason about than the lint is worth.
        //   unused_qualifications (829) — every path is fully qualified on
        //     purpose: this file is `include!`d into azul-dll, so an unqualified
        //     name would resolve against whatever the host module imported.
        //   unreachable_pub (310) — `pub` on items inside a private module,
        //     which is exactly how this module is structured.
        //   non_upper_case_globals (253) — constant names come from api.json and
        //     must match the C ABI spelling, not Rust convention.
        //   variant_size_differences (234) — FFI enum layout is dictated by
        //     api.json; the generator has no freedom to box a large variant.
        //   elided_lifetimes_in_paths (59), let_underscore_drop (51),
        //   missing_copy_implementations / missing_debug_implementations (127).
        //
        // Deliberately NOT allowed, so they keep reporting: private_interfaces,
        // dead_code, unknown_lints, and anything unsafe-related.
        builder.line("#![allow(");
        builder.line("    trivial_casts,");
        builder.line("    trivial_numeric_casts,");
        builder.line("    unused_qualifications,");
        builder.line("    unreachable_pub,");
        builder.line("    non_upper_case_globals,");
        builder.line("    variant_size_differences,");
        builder.line("    elided_lifetimes_in_paths,");
        builder.line("    let_underscore_drop,");
        builder.line("    missing_copy_implementations,");
        builder.line("    missing_debug_implementations,");
        // unsafe_op_in_unsafe_fn (17199 — the single largest category, and the
        // one that was truncating the log). Allowed here after some hesitation,
        // because it is an UNSAFETY lint and those should normally stay loud.
        //
        // The reasoning: every function in this module is an `extern "C"` ABI
        // shim whose body is unsafe in its entirety — a transmute, a raw-pointer
        // deref, a Vec::from_raw_parts, or a call through a function pointer
        // supplied by the caller. The lint asks the author to delimit WHICH part
        // is unsafe, which is useful in hand-written code where an unsafe fn
        // contains mostly safe logic. Here the answer is always "all of it", so
        // the lint reports 17199 times and distinguishes nothing.
        //
        // The alternative is to wrap every generated body in `unsafe { }`, which
        // would satisfy the lint but nest inside the blocks the emitters already
        // produce and trade 17199 of these for a comparable pile of
        // `unused_unsafe`. Fixing the ONE emitter that was easy to fix
        // (transmute_helpers, 6370 sites) is done and stays done.
        //
        // What actually reviews unsafety in this file is not this lint: it is
        // the ffi_safety_tests job, the ASan/UBSan/TSan runs over the C
        // examples, and the Miri leg — all of which exercise the generated ABI
        // rather than reading it.
        builder.line("    unsafe_op_in_unsafe_fn,");
        builder.line(")]");
        builder.line("pub mod dll {");
        builder.indent();

        // Imports
        for import in &config.imports {
            builder.line(import);
        }
        if !config.imports.is_empty() {
            builder.blank();
        }

        // GL type aliases
        shared::generate_gl_type_aliases(&mut builder);

        // Type definitions
        if config.struct_mode != StructMode::None {
            let types = self.generate_types(ir, config)?;
            builder.raw(&types);
        }

        // Trait implementations using transmute
        let trait_impls = self.generate_trait_impls(ir, config)?;
        builder.raw(&trait_impls);

        // C-ABI functions with bodies (using transmute to/from internal types)
        let functions = self.generate_functions(ir, config)?;
        builder.raw(&functions);

        // End module wrappers
        builder.dedent();
        builder.line("} // mod dll");
        builder.dedent();
        builder.line("} // mod __dll_api_inner");

        // Re-exports at crate root
        builder.blank();
        builder.line("pub use __dll_api_inner::dll::*;");

        // Generate tests if enabled
        if config.generate_tests {
            builder.blank();
            Self::generate_tests_impl(&mut builder, ir, config)?;
        }

        Ok(builder.finish())
    }

    fn generate_types(&self, ir: &CodegenIR, config: &CodegenConfig) -> Result<String> {
        let mut builder = CodeBuilder::new(&config.indent);
        shared::generate_types(&mut builder, ir, config);
        Ok(builder.finish())
    }

    fn generate_functions(&self, ir: &CodegenIR, config: &CodegenConfig) -> Result<String> {
        let mut builder = CodeBuilder::new(&config.indent);

        builder.line("// --- C-ABI Functions ---");
        builder.blank();

        // Skip trait functions when using transmute (traits are implemented directly)
        let skip_trait_functions =
            matches!(config.trait_impl_mode, TraitImplMode::UsingTransmute { .. });

        for func in &ir.functions {
            if !config.should_include_type(&func.class_name) {
                continue;
            }
            // Skip trait functions if we're implementing traits via transmute
            if skip_trait_functions && func.kind.is_trait_function() {
                continue;
            }
            Self::generate_function_with_body(&mut builder, func, config)?;
        }

        Ok(builder.finish())
    }

    fn generate_trait_impls(&self, ir: &CodegenIR, config: &CodegenConfig) -> Result<String> {
        let mut builder = CodeBuilder::new(&config.indent);

        builder.line("// --- Trait Implementations ---");
        builder.blank();

        match &config.trait_impl_mode {
            TraitImplMode::UsingTransmute { external_crate } => {
                for struct_def in &ir.structs {
                    if !config.should_include_type(&struct_def.name) {
                        continue;
                    }
                    Self::generate_transmute_trait_impls(
                        &mut builder,
                        struct_def,
                        config,
                        external_crate,
                    );
                }
                for enum_def in &ir.enums {
                    if !config.should_include_type(&enum_def.name) {
                        continue;
                    }
                    Self::generate_transmute_trait_impls_enum(
                        &mut builder,
                        enum_def,
                        config,
                        external_crate,
                    );
                }
            }
            TraitImplMode::UsingDerive => {
                // With derive, traits are already on the type definitions
            }
            TraitImplMode::UsingCAPI | TraitImplMode::None => {
                // These modes don't apply to static binding
            }
        }

        Ok(builder.finish())
    }
}

impl RustStaticGenerator {
    /// Generate transmute-based trait impls for a struct
    fn generate_transmute_trait_impls(
        builder: &mut CodeBuilder,
        struct_def: &StructDef,
        config: &CodegenConfig,
        _external_crate: &str,
    ) {
        let name = config.apply_prefix(&struct_def.name);

        // Build generics string
        let generics = if struct_def.generic_params.is_empty() {
            String::new()
        } else {
            format!("<{}>", struct_def.generic_params.join(", "))
        };
        let full_name = format!("{}{}", name, generics);

        // Get external path
        let Some(external_path) = &struct_def.external_path else {
            return;
        };
        let external_path = config.transform_external_path(external_path);

        // Clone trait - generate via transmute only if Clone is in custom_impls (not derived)
        // Types with clone_is_derived get Clone via #[derive(Clone)] in generate_struct
        if struct_def.traits.is_clone && !struct_def.traits.clone_is_derived {
            builder.line(&format!("impl{} Clone for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn clone(&self) -> Self {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute((transmute::<_, &{}>(&self)).clone()) }}",
                external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // Drop trait (if has custom destructor)
        if struct_def.traits.has_custom_drop {
            builder.line(&format!("impl{} Drop for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn drop(&mut self) {");
            builder.indent();
            builder.line(&format!(
                "let _ = unsafe {{ transmute::<_, {}>(*transmute::<_, &{}>(self)) }};",
                external_path, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // PartialEq, Hash, PartialOrd, Ord, Eq as needed
        Self::generate_comparison_traits(
            builder,
            &full_name,
            &generics,
            &external_path,
            &struct_def.traits,
        );
    }

    /// Generate transmute-based trait impls for an enum
    fn generate_transmute_trait_impls_enum(
        builder: &mut CodeBuilder,
        enum_def: &EnumDef,
        config: &CodegenConfig,
        _external_crate: &str,
    ) {
        let name = config.apply_prefix(&enum_def.name);

        let generics = if enum_def.generic_params.is_empty() {
            String::new()
        } else {
            format!("<{}>", enum_def.generic_params.join(", "))
        };
        let full_name = format!("{}{}", name, generics);

        let Some(external_path) = &enum_def.external_path else {
            return;
        };
        let external_path = config.transform_external_path(external_path);

        // Clone trait - generate via transmute only if Clone is in custom_impls (not derived)
        // Types with clone_is_derived get Clone via #[derive(Clone)] in generate_enum
        if enum_def.traits.is_clone && !enum_def.traits.clone_is_derived {
            builder.line(&format!("impl{} Clone for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn clone(&self) -> Self {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute((transmute::<_, &{}>(&self)).clone()) }}",
                external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // Drop trait
        if enum_def.traits.has_custom_drop {
            builder.line(&format!("impl{} Drop for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn drop(&mut self) {");
            builder.indent();
            builder.line(&format!(
                "let _ = unsafe {{ transmute::<_, {}>(*transmute::<_, &{}>(self)) }};",
                external_path, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        Self::generate_comparison_traits(
            builder,
            &full_name,
            &generics,
            &external_path,
            &enum_def.traits,
        );
    }

    /// Generate comparison traits (PartialEq, Hash, PartialOrd, Ord, Eq)
    fn generate_comparison_traits(
        builder: &mut CodeBuilder,
        full_name: &str,
        generics: &str,
        external_path: &str,
        traits: &TypeTraits,
    ) {
        // PartialEq
        if traits.is_partial_eq {
            builder.line(&format!("impl{} PartialEq for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn eq(&self, other: &Self) -> bool {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute::<_, &{}>(&self) == transmute::<_, &{}>(&other) }}",
                external_path, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // Eq
        if traits.is_eq {
            builder.line(&format!("impl{} Eq for {} {{}}", generics, full_name));
            builder.blank();
        }

        // Hash
        if traits.is_hash {
            builder.line(&format!(
                "impl{} core::hash::Hash for {} {{",
                generics, full_name
            ));
            builder.indent();
            builder.line("fn hash<H: core::hash::Hasher>(&self, state: &mut H) {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute::<_, &{}>(&self).hash(state) }}",
                external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // PartialOrd
        if traits.is_partial_ord {
            builder.line(&format!("impl{} PartialOrd for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn partial_cmp(&self, other: &Self) -> Option<core::cmp::Ordering> {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute::<_, &{}>(&self).partial_cmp(transmute::<_, &{}>(&other)) }}",
                external_path, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        // Ord
        if traits.is_ord {
            builder.line(&format!("impl{} Ord for {} {{", generics, full_name));
            builder.indent();
            builder.line("fn cmp(&self, other: &Self) -> core::cmp::Ordering {");
            builder.indent();
            builder.line(&format!(
                "unsafe {{ transmute::<_, &{}>(&self).cmp(transmute::<_, &{}>(&other)) }}",
                external_path, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.dedent();
            builder.line("}");
            builder.blank();
        }
    }

    /// Generate a single function with its transmute-based body
    fn generate_function_with_body(
        builder: &mut CodeBuilder,
        func: &FunctionDef,
        config: &CodegenConfig,
    ) -> Result<()> {
        // Doc comment
        if !func.doc.is_empty() {
            for doc_line in &func.doc {
                builder.line(&format!("/// {}", doc_line));
            }
        }

        // #[no_mangle] gated behind export feature
        if let CAbiFunctionMode::InternalBindings { export_feature } = &config.cabi_functions {
            builder.line(&format!(
                "#[cfg_attr(feature = \"{export_feature}\", no_mangle)]"
            ));
            builder.line("#[inline]");
        }

        // Function signature
        let fn_name = &func.c_name;
        let args = Self::format_fn_args(&func.args, config);
        let return_type = func
            .return_type
            .as_ref()
            .map(|r| format!(" -> {}", config.apply_prefix(r)))
            .unwrap_or_default();

        builder.line(&format!(
            "pub extern \"C\" fn {}({}){} {{",
            fn_name, args, return_type
        ));
        builder.indent();

        // Generate function body using transmute
        if let Some(ref fn_body) = func.fn_body {
            // Use the fn_body from api.json
            for line in fn_body.lines() {
                builder.line(line);
            }
        } else {
            // Generate placeholder body
            builder.line("unimplemented!()");
        }

        builder.dedent();
        builder.line("}");
        builder.blank();

        Ok(())
    }

    /// Format function arguments for signature
    fn format_fn_args(args: &[FunctionArg], config: &CodegenConfig) -> String {
        args.iter()
            .map(|arg| {
                let type_name = config.apply_prefix(&arg.type_name);
                let ref_prefix = match arg.ref_kind {
                    ArgRefKind::Owned => "",
                    ArgRefKind::Ref => "&",
                    ArgRefKind::RefMut => "&mut ",
                    ArgRefKind::Ptr => "*const ",
                    ArgRefKind::PtrMut => "*mut ",
                };
                format!("{}: {}{}", arg.name, ref_prefix, type_name)
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    /// Generate test functions
    fn generate_tests_impl(
        builder: &mut CodeBuilder,
        ir: &CodegenIR,
        config: &CodegenConfig,
    ) -> Result<()> {
        builder.line("#[cfg(test)]");
        builder.line("mod generated_tests {");
        builder.indent();
        builder.line("use super::dll;");
        builder.line("use core::mem;");
        builder.blank();

        // Generate size/alignment tests for structs and enums
        for struct_def in &ir.structs {
            if !config.should_include_type(&struct_def.name) {
                continue;
            }
            if !struct_def.generic_params.is_empty() {
                continue;
            }
            let Some(external_path) = &struct_def.external_path else {
                continue;
            };
            if external_path.contains('<') {
                continue;
            }

            let external_path = config.transform_external_path(external_path);
            let generated_type = format!("dll::Az{}", struct_def.name);
            let test_name = format!("test_size_align_{}", struct_def.name.to_lowercase());

            builder.line("#[test]");
            builder.line(&format!("fn {}() {{", test_name));
            builder.indent();
            builder.line(&format!(
                "assert_eq!(mem::size_of::<{}>(), mem::size_of::<{}>());",
                generated_type, external_path
            ));
            builder.line(&format!(
                "assert_eq!(mem::align_of::<{}>(), mem::align_of::<{}>());",
                generated_type, external_path
            ));
            builder.dedent();
            builder.line("}");
            builder.blank();
        }

        builder.dedent();
        builder.line("} // mod generated_tests");

        Ok(())
    }
}
