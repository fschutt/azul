//! LuaRocks rockspec emission for the `azul` package.
//!
//! The native shared library (`libazul.{so,dylib,dll}`) is **bundled
//! separately**: the rockspec only ships the Lua glue file (`azul.lua`),
//! which runs unchanged under LuaJIT (built-in `ffi`) and under PUC Lua
//! with the `cffi-lua` rock (see `lang_lua/mod.rs`). Users must place the
//! prebuilt native library somewhere `ffi.load("azul")` can find it
//! (system library path, `LD_LIBRARY_PATH`, `DYLD_LIBRARY_PATH`, `PATH`,
//! or alongside the executable).

/// Generate the contents of `azul-<version>-1.rockspec` as a String.
///
/// LuaRocks requires the filename to match `<package>-<version>.rockspec`
/// exactly (it rejects a filename/content mismatch), so the emitted file
/// MUST be written as `azul-{version}-1.rockspec`. The write site lives in
/// `generator.rs`; the deploy copy-list (`doc/src/dllgen/deploy.rs`)
/// computes the same name — all three derive from `ir.api_version`.
///
/// `source.url` points at the released single-file binding on azul.rs —
/// LuaRocks fetches non-archive URLs as plain files, and `build.modules`
/// maps it to the `azul` module, so `require('azul')` resolves to the
/// dual-runtime file under both interpreters.
pub fn generate_rockspec(version: &str) -> String {
    format!(
        r#"-- azul-{version}-1.rockspec
-- Auto-generated by azul-doc codegen v2
--
-- This rockspec installs ONLY the Lua FFI glue (azul.lua). The file runs
-- unchanged under LuaJIT 2.0+ (built-in `ffi`) and under PUC Lua 5.1+ with
-- the cffi-lua module (`luarocks install cffi-lua`), whose API mirrors
-- LuaJIT's. LuaRocks cannot express "cffi-lua, but only when the
-- interpreter is not LuaJIT", so that dependency is documented here rather
-- than listed; azul.lua reports a clear error when neither FFI module
-- loads.
--
-- The native shared library (libazul.so / .dylib / azul.dll) must be
-- obtained separately and placed where `ffi.load("azul")` can locate it
-- (system library path, LD_LIBRARY_PATH on Linux, DYLD_LIBRARY_PATH on
-- macOS, or PATH on Windows).

package = "azul"
version = "{version}-1"

source = {{
    -- Single-file source: LuaRocks downloads non-archive URLs as-is,
    -- and build.modules below maps the file to the `azul` module.
    url = "https://azul.rs/ui/release/{version}/azul.lua",
    -- Replace with actual hash before publishing.
    -- md5 = "...",
}}

description = {{
    summary  = "Lua FFI bindings (LuaJIT / cffi-lua) for the Azul GUI framework",
    detailed = [[
        Azul is a desktop GUI framework. This rock provides idiomatic Lua
        bindings on top of the LuaJIT `ffi` module or, under PUC Lua, the
        cffi-lua module (install it separately with `luarocks install
        cffi-lua`). The native shared library is distributed separately
        and must be available on the dynamic loader's search path at
        runtime.
    ]],
    homepage = "https://azul.rs",
    license  = "MPL-2.0 OR MIT OR Apache-2.0",
    maintainer = "Azul contributors",
}}

dependencies = {{
    "lua >= 5.1",
    -- LuaJIT (built-in ffi) or PUC Lua + cffi-lua (`luarocks install
    -- cffi-lua`). Neither can be expressed as a conditional dependency in
    -- a portable rockspec; azul.lua validates the FFI module at load time.
}}

build = {{
    type = "builtin",
    modules = {{
        azul = "azul.lua",
    }},
}}
"#,
    )
}
