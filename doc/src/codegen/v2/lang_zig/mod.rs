//! Zig binding generator.
//!
//! Emits ONE source file, `azul.zig`, in three layers:
//!
//! 1. `pub const C = struct { ... }` — the C ABI of `libazul` pre-translated from the IR (see
//!    [`c_decls`]): every struct/union/enum, callback typedef, constant and `pub extern fn`,
//!    with the names and layouts of `azul.h`.
//! 2. The runtime prelude ([`ZIG_RUNTIME`]): `ReflectModel(T)` (the user's data model behind a
//!    `RefAny`) and the comptime `_as*` conversions the wrappers call so users can pass Zig
//!    slices, `?T`, wrapper structs and plain Zig `fn`s where the C ABI wants `AzString`,
//!    `AzOption*`, an owned struct or a `callconv(.c)` function pointer.
//! 3. Idiomatic wrapper structs with `deinit()` and lowerCamel methods around the heap-owning
//!    types ([`wrappers`]), so users write `defer app.deinit();` instead of `C.AzApp_delete(&app)`.
//!
//! Plus a ready-to-use `build.zig` ([`build_zig::generate_build_zig`]).
//!
//! # Why not `@cImport(@cInclude("azul.h"))`?
//!
//! That is what this generator did first, and it is the smallest possible binding: Zig
//! translates the C header itself. But `azul.h` is 5.6 MB (the types, ~20k `extern`
//! declarations and ~100k lines of `static inline` helpers), and Zig re-translates and
//! analyses the whole translation unit on every cold build — 91–123 s for a hello-world,
//! ~5 s warm, 28 s in `ReleaseSafe`. Emitting the declarations from the IR, the way every
//! other binding gets them, costs a few seconds instead and drops the header from the
//! include path entirely. The pre-translation keeps the `translate-c` spellings (`[*c]`
//! pointers, `c_uint` enums with `c_int` constants, zeroed struct defaults), so code that was
//! written against the `@cImport` namespace compiles unchanged.
//!
//! # Build / link requirements
//!
//! Users must:
//!
//! 1. put `azul.zig` next to their source and `@import("azul.zig")` it,
//! 2. link the `azul` system library (e.g. `exe.linkSystemLibrary("azul", .{});` and
//!    `exe.addLibraryPath(b.path("."));`),
//! 3. link `libc` (`.link_libc = true`).
//!
//! No header, no include path.

pub mod build_zig;
pub mod c_decls;
pub mod wrappers;

use anyhow::Result;

use super::{config::CodegenConfig, generator::CodeBuilder, ir::CodegenIR};

/// The C library name used in `linkSystemLibrary("azul")`.
/// Must match the prebuilt artifact name (`libazul.so` / `libazul.dylib`
/// / `azul.dll`).
pub const LIB_NAME: &str = "azul";

/// Generate the full `azul.zig` source file (see the module docs for the three layers).
///
/// `config` is currently unused (Zig bindings have no per-target
/// dialects) but is taken by reference to match the signatures of
/// other language entry points.
pub fn generate(ir: &CodegenIR, _config: &CodegenConfig) -> Result<String> {
    let mut builder = CodeBuilder::new("    ");

    emit_header(&mut builder);
    emit_c_namespace(&mut builder, ir, &CodegenConfig::c_header());
    builder.raw(ZIG_RUNTIME);
    builder.raw(&wrappers::generate_wrappers(ir));

    Ok(builder.finish())
}

