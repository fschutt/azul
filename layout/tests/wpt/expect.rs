//! The known-failures mechanism both suites share: which cases are expected
//! not to pass, the gate, the summary, the results files and blessing.
//!
//! An expectation file lists every case that is expected NOT to pass, one per
//! line:
//!
//! ```text
//! FAIL css/CSS2/tables/border-collapse-005.html E-TABLE-BC # the table overlaps the text below it
//! ERROR@macos local/table/x.html E-TABLE
//! UNSUPPORTED bold-799c67d8 E-EDIT-FORMAT
//! ```
//!
//! The status says how the case failed when it was listed; any non-pass keeps
//! matching (a FAIL that turns into an ERROR is not a regression, just
//! different). `@os[,os]` limits a line to `macos`, `linux` or `windows`. The
//! gap id names the engine gap (scripts/REFCI_2026_09_30.md); text after `#`
//! is a note and survives blessing.

use std::{
    collections::BTreeMap,
    fmt::Write as _,
    path::{Path, PathBuf},
    time::Instant,
};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    Pass,
    /// Ran, and the result is wrong.
    Fail,
    /// Could not run: a parse or layout error, a panic, or a case the harness
    /// could not set up.
    Error,
    /// The engine has no operation for what the case asks (an editing command
    /// with no azul equivalent).
    Unsupported,
}

impl Outcome {
    pub const fn label(self) -> &'static str {
        match self {
            Self::Pass => "PASS",
            Self::Fail => "FAIL",
            Self::Error => "ERROR",
            Self::Unsupported => "UNSUPPORTED",
        }
    }
}

/// One case's result.
pub struct CaseResult {
    pub id: String,
    pub outcome: Outcome,
    /// The engine gap the case probes ("-" when the data names none).
    pub gap: String,
    /// One line: why it failed, or what was measured.
    pub detail: String,
}

struct Listed {
    status: String,
    gap: String,
    note: String,
}

/// A suite's expectation file.
pub struct Expectations {
    path: PathBuf,
    header: Vec<String>,
    /// The ids expected not to pass on this OS.
    listed: BTreeMap<String, Listed>,
    /// Lines for other operating systems, kept verbatim on blessing.
    other_os: Vec<String>,
}

pub fn this_os() -> &'static str {
    if cfg!(target_os = "macos") {
        "macos"
    } else if cfg!(target_os = "windows") {
        "windows"
    } else {
        "linux"
    }
}

impl Expectations {
    /// A missing file lists nothing (every failure is then a regression).
    pub fn load(path: &Path) -> Self {
        let mut header = Vec::new();
        let mut listed = BTreeMap::new();
        let mut other_os = Vec::new();
        let text = std::fs::read_to_string(path).unwrap_or_default();
        let mut in_header = true;
        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with('#') {
                if in_header {
                    header.push(line.to_string());
                }
                continue;
            }
            in_header = false;
            let (body, note) = match trimmed.split_once('#') {
                Some((b, n)) => (b.trim(), n.trim().to_string()),
                None => (trimmed, String::new()),
            };
            let mut words = body.split_whitespace();
            let (Some(status), Some(id)) = (words.next(), words.next()) else {
                continue;
            };
            let gap = words.next().unwrap_or("-").to_string();
            let (status, oses) = match status.split_once('@') {
                Some((s, o)) => (s, Some(o)),
                None => (status, None),
            };
            if let Some(oses) = oses {
                if !oses.split(',').any(|o| o.trim() == this_os()) {
                    other_os.push(line.to_string());
                    continue;
                }
            }
            listed.insert(
                id.to_string(),
                Listed {
                    status: status.to_string(),
                    gap,
                    note,
                },
            );
        }
        Self {
            path: path.to_path_buf(),
            header,
            listed,
            other_os,
        }
    }

    fn is_listed(&self, id: &str) -> bool {
        self.listed.contains_key(id)
    }

    /// The file as it should be after this run.
    fn blessed(&self, results: &[CaseResult], suite: &str) -> String {
        let mut out = String::new();
        if self.header.is_empty() {
            let _ = writeln!(
                out,
                "# Known failures of the WPT {suite} suite (layout/tests/wpt/). Generated by\n\
                 # AZ_WPT_BLESS=1; keep the notes after '#'. Format: STATUS[@os] id gap [# note]."
            );
        } else {
            for h in &self.header {
                let _ = writeln!(out, "{h}");
            }
        }
        let mut lines: Vec<String> = results
            .iter()
            .filter(|r| r.outcome != Outcome::Pass)
            .map(|r| {
                let listed = self.listed.get(&r.id);
                let gap = listed
                    .map(|l| l.gap.as_str())
                    .filter(|g| *g != "-")
                    .unwrap_or(r.gap.as_str());
                let note = listed.map(|l| l.note.as_str()).unwrap_or_default();
                let mut line = format!("{} {} {}", r.outcome.label(), r.id, gap);
                if !note.is_empty() {
                    let _ = write!(line, " # {note}");
                }
                line
            })
            .collect();
        lines.extend(self.other_os.iter().cloned());
        lines.sort_by(|a, b| id_of(a).cmp(id_of(b)).then_with(|| a.cmp(b)));
        for l in lines {
            let _ = writeln!(out, "{l}");
        }
        out
    }
}

fn id_of(line: &str) -> &str {
    line.split_whitespace().nth(1).unwrap_or("")
}

/// Compare with the expectations, print the summary, write the result files
/// (and bless when asked). `true` = no regression and no unexpected pass.
pub fn gate(
    suite: &str,
    results: &[CaseResult],
    exp: &Expectations,
    out: &Path,
    started: Instant,
) -> bool {
    let show: usize = std::env::var("AZ_WPT_SHOW")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(20);
    let count = |o: Outcome| results.iter().filter(|r| r.outcome == o).count();
    let regressions: Vec<&CaseResult> = results
        .iter()
        .filter(|r| r.outcome != Outcome::Pass && !exp.is_listed(&r.id))
        .collect();
    let unexpected: Vec<&CaseResult> = results
        .iter()
        .filter(|r| r.outcome == Outcome::Pass && exp.is_listed(&r.id))
        .collect();
    let failing: Vec<&CaseResult> = results
        .iter()
        .filter(|r| r.outcome != Outcome::Pass)
        .collect();

    // libtest's count line, so scripts/zero_test_guard.sh sees a real run.
    println!("\nrunning {} tests", results.len());
    println!(
        "wpt {suite}: {} cases - {} pass, {} fail, {} error, {} unsupported ({})",
        results.len(),
        count(Outcome::Pass),
        count(Outcome::Fail),
        count(Outcome::Error),
        count(Outcome::Unsupported),
        this_os(),
    );
    println!(
        "  expected not to pass: {}, regressions: {}, unexpected passes: {}",
        failing.len() - regressions.len(),
        regressions.len(),
        unexpected.len()
    );

    // The backlog: failures by engine gap.
    let mut by_gap: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    for r in results {
        let e = by_gap.entry(r.gap.as_str()).or_default();
        e.1 += 1;
        if r.outcome != Outcome::Pass {
            e.0 += 1;
        }
    }
    let mut gaps: Vec<String> = by_gap
        .iter()
        .filter(|(_, (f, _))| *f > 0)
        .map(|(g, (f, t))| format!("{g} {f}/{t}"))
        .collect();
    gaps.sort();
    if !gaps.is_empty() {
        println!("  not passing by engine gap: {}", gaps.join(", "));
    }

    if !regressions.is_empty() {
        println!(
            "  REGRESSIONS - not passing and not in {}:",
            exp.path.display()
        );
        for r in regressions.iter().take(show.max(1)) {
            println!(
                "    {:<11} {} [{}] {}",
                r.outcome.label(),
                r.id,
                r.gap,
                r.detail
            );
        }
        if regressions.len() > show.max(1) {
            println!("    ... and {} more", regressions.len() - show.max(1));
        }
    }
    if !unexpected.is_empty() {
        println!(
            "  UNEXPECTED PASSES - take them out of {}:",
            exp.path.display()
        );
        for r in unexpected.iter().take(show.max(1)) {
            println!("    {} [{}]", r.id, r.gap);
        }
        if unexpected.len() > show.max(1) {
            println!("    ... and {} more", unexpected.len() - show.max(1));
        }
    }
    if regressions.is_empty() && show > 0 && !failing.is_empty() {
        println!(
            "  first {} of {} expected failures:",
            show.min(failing.len()),
            failing.len()
        );
        for r in failing.iter().take(show) {
            println!(
                "    {:<11} {} [{}] {}",
                r.outcome.label(),
                r.id,
                r.gap,
                r.detail
            );
        }
    }

    // Files: every result, and the expectations this run implies.
    let mut tsv = String::from("# id\toutcome\tgap\tlisted\tdetail\n");
    for r in results {
        let _ = writeln!(
            tsv,
            "{}\t{}\t{}\t{}\t{}",
            r.id,
            r.outcome.label(),
            r.gap,
            if exp.is_listed(&r.id) {
                exp.listed.get(&r.id).map_or("", |l| l.status.as_str())
            } else {
                "-"
            },
            r.detail.replace(['\t', '\n'], " ")
        );
    }
    let _ = std::fs::write(out.join(format!("{suite}_results.tsv")), tsv);
    let blessed = exp.blessed(results, suite);
    let _ = std::fs::write(
        out.join(format!("{suite}_expectations.suggested.txt")),
        &blessed,
    );
    let bless = std::env::var_os("AZ_WPT_BLESS").is_some_and(|v| v != "0");
    if bless {
        match std::fs::write(&exp.path, &blessed) {
            Ok(()) => println!("  blessed: wrote {}", exp.path.display()),
            Err(e) => println!("  could not bless {}: {e}", exp.path.display()),
        }
    }
    println!(
        "  results: {}",
        out.join(format!("{suite}_results.tsv")).display()
    );

    let ok = bless || (regressions.is_empty() && unexpected.is_empty());
    println!(
        "test result: {}. {} passed; {} failed; 0 ignored; 0 measured; 0 filtered out; finished in {:.2}s",
        if ok { "ok" } else { "FAILED" },
        count(Outcome::Pass),
        failing.len(),
        started.elapsed().as_secs_f64()
    );
    ok
}
