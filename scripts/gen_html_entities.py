#!/usr/bin/env python3
"""Writes core/src/xml_entities.rs: the HTML Standard's named character references.

    python3 scripts/gen_html_entities.py

The table is Python's `html.entities.html5`, which is the HTML Standard's
(https://html.spec.whatwg.org/multipage/named-characters.html): 2231 names, of
which 106 legacy ones also appear without their `;` (`&amp`, `&copy`, `&nbsp`).
Every value is written as `\\u{..}` escapes, so the file is ASCII.
"""

import html.entities
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "core", "src", "xml_entities.rs")

HEADER = """//! The HTML named character references: the HTML Standard's whole table
//! (<https://html.spec.whatwg.org/multipage/named-characters.html>, {count}
//! names). GENERATED by `scripts/gen_html_entities.py` from Python's
//! `html.entities.html5` (the same table); do not edit by hand.

/// `(name, characters)`, sorted by name (byte order) for a binary search. A
/// name ends with `;` as HTML spells it (`"copy;"`); the {legacy} legacy names
/// a browser also reads WITHOUT the `;` (`&copy 2026`) are in the table a second
/// time without it (`"copy"`). Most names stand for one character, {multi} for
/// two (`"NotEqualTilde;"` is U+2242 U+0338).
pub(super) static HTML5_NAMED_REFERENCES: &[(&str, &str)] = &[
"""


def rust_str(value):
    return "".join("\\u{%X}" % ord(c) for c in value)


def main():
    table = html.entities.html5
    names = sorted(table.keys(), key=lambda k: k.encode("utf-8"))
    legacy = sum(1 for k in names if not k.endswith(";"))
    multi = sum(1 for k in names if len(table[k]) > 1)
    out = [HEADER.format(count=len(names), legacy=legacy, multi=multi)]
    for name in names:
        out.append('    ("%s", "%s"),\n' % (name, rust_str(table[name])))
    out.append("];\n")
    with open(OUT, "w", encoding="ascii") as f:
        f.write("".join(out))
    print("wrote %s: %d names (%d legacy, %d two-character)" % (OUT, len(names), legacy, multi))


if __name__ == "__main__":
    main()
