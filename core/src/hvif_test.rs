#[test]
fn a_gradient_keeps_its_transform_and_a_negative_float24_keeps_its_sign() {
    let icon = Hvif::parse(&INFO).expect("an HVIF icon");
    // The store's SVG of it: a radial gradient #0530d1 -> #67b5ff with
    // gradientTransform="matrix(0.3125,0,0,0.1406,30,22)".
    let radial = icon
        .styles
        .iter()
        .find_map(|s| match s {
            HvifStyle::Gradient(g) if g.kind == HvifGradientKind::Circular
                && g.stops[0].color == (HvifRgba { r: 0x05, g: 0x30, b: 0xd1, a: 255 }) => Some(g),
            _ => None,
        })
        .expect("the radial gradient");
    let m = radial.transform;
    assert!(close(m.a, 0.3125) && close(m.b, 0.0) && close(m.c, 0.0), "{m:?}");
    assert!(close(m.d, 0.1406) && close(m.e, 30.0) && close(m.f, 22.0), "{m:?}");
    // A float24 with its sign bit set reads negative (the `hvif` crate's
    // reader lost it): New Mail File's paper gradient has c = -0.55.
    let paper = Hvif::parse(&NEW_MAIL_FILE).expect("an HVIF icon");
    let HvifStyle::Gradient(gradient) = &paper.styles[paper.shapes[2].style] else {
        panic!("the paper is a gradient: {:?}", paper.styles);
    };
    assert!(gradient.transform.c < -0.5, "{:?}", gradient.transform);
}

#[test]
fn bytes_that_are_no_icon_or_end_early_are_an_error() {
    assert_eq!(Hvif::parse(b"PNG..."), Err(HvifError::NotHvif));
    assert!(!is_hvif(b"nci"));
    assert_eq!(Hvif::parse(&NEW_MAIL_FILE[..60]), Err(HvifError::Truncated));
    assert_eq!(Hvif::parse(b"ncif"), Err(HvifError::Truncated));
}

#[test]
fn a_shape_is_drawn_only_at_its_level_of_detail() {
    let shape = HvifShape {
        style: 0,
        paths: Vec::new(),
        transform: HvifAffine::IDENTITY,
        hinting: false,
        min_scale: lod(51),
        max_scale: lod(255),
        transformers: Vec::new(),
    };
    assert!(!shape.visible_at(0.25), "not at 16 px");
    assert!(shape.visible_at(1.0), "at 64 px");
}

