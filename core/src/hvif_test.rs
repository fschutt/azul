fn close(a: f32, b: f32) -> bool {
    (a - b).abs() < 0.05
}

#[test]
fn an_icon_is_read_into_its_styles_paths_and_shapes() {
    let icon = Hvif::parse(&NEW_MAIL_FILE).expect("an HVIF icon");
    assert_eq!(icon.shapes.len(), 5, "{icon:?}");
    // The shadow: #010101 at 120 / 255.
    let shadow = &icon.shapes[0];
    assert_eq!(
        icon.styles[shadow.style],
        HvifStyle::Solid(HvifRgba { r: 1, g: 1, b: 1, a: 120 })
    );
    // Its outline: M39 56 L42 57 C42 57 62 40 62 37 ...
    let path = &icon.paths[shadow.paths[0]];
    assert!(path.closed);
    let (p0, p1, p2) = (path.points[0], path.points[1], path.points[2]);
    assert!(close(p0.x, 39.0) && close(p0.y, 56.0), "{p0:?}");
    assert!(close(p1.x, 42.0) && close(p1.y, 57.0), "{p1:?}");
    assert!(close(p2.x, 62.0) && close(p2.y, 37.0), "{p2:?}");
    assert!(close(p2.in_x, 62.0) && close(p2.in_y, 40.0), "the curve's handle into it: {p2:?}");
    // The outline stroke: 4 wide, round joins.
    let (width, join, _, _) = icon.shapes[1].stroke().expect("a stroke");
    assert!(close(width, 4.0) && join == HvifLineJoin::Round);
}

