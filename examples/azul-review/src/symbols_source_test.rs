#[test]
fn a_memory_source_lists_a_folder_with_its_files_and_folders_in_name_order() {
    let m = mem(&[("b.rs", "12345"), ("a/x.rs", "1"), ("a/y/z.rs", "22"), ("c/d.rs", "")]);
    let root = m.list("").unwrap();
    let names: Vec<(&str, EntryKind)> = root.iter().map(|e| (e.name.as_str(), e.kind)).collect();
    assert_eq!(names, [("a", EntryKind::Dir), ("b.rs", EntryKind::File), ("c", EntryKind::Dir)]);
    assert_eq!(root[1].size, 5);
    let a = m.list("a").unwrap();
    let names: Vec<(&str, EntryKind)> = a.iter().map(|e| (e.name.as_str(), e.kind)).collect();
    assert_eq!(names, [("x.rs", EntryKind::File), ("y", EntryKind::Dir)]);
    assert!(m.list("nothing").unwrap().is_empty());
}

#[test]
fn a_memory_source_reads_stats_and_refuses_a_file_over_the_cap() {
    let mut m = MemSource::new();
    m.put_at("a.rs", b"fn a() {}".to_vec(), 1_700_000_000_000);
    assert_eq!(m.read("a.rs", 100).unwrap(), b"fn a() {}");
    assert_eq!(m.read("a.rs", 4), Err(ReadError::TooLarge(9)));
    assert_eq!(m.read("b.rs", 100), Err(ReadError::NotFound));
    assert_eq!(m.stat("a.rs"), Some(FileMeta { size: 9, mtime_ms: 1_700_000_000_000 }));
    assert_eq!(m.stat("b.rs"), None);
}

#[test]
fn a_memory_source_remembers_what_was_read_in_order() {
    let m = mem(&[("a.rs", "1"), ("b.rs", "2"), ("c.rs", "3")]);
    let _ = m.read("c.rs", 10);
    let _ = m.read("a.rs", 10);
    let _ = m.read("nothing.rs", 10);
    assert_eq!(m.reads(), ["c.rs", "a.rs", "nothing.rs"]);
}

#[test]
fn a_path_that_leaves_the_workspace_is_refused_by_both_sources() {
    let m = mem(&[("a.rs", "1")]);
    let tmp = Tmp::new("outside");
    tmp.file("a.rs", "1");
    let d = DiskSource::new(tmp.0.clone());
    for bad in ["../a.rs", "a/../../x", "/etc/passwd", "a//b", "..", "a\\..\\b"] {
        assert_eq!(m.read(bad, 10), Err(ReadError::Outside), "{bad}");
        assert_eq!(d.read(bad, 10), Err(ReadError::Outside), "{bad}");
        assert!(m.list(bad).is_err(), "{bad}");
        assert!(d.list(bad).is_err(), "{bad}");
        assert_eq!(d.stat(bad), None, "{bad}");
    }
}

#[test]
fn a_disk_source_lists_reads_and_stats_a_real_folder() {
    let tmp = Tmp::new("real");
    tmp.file("src/lib.rs", "pub struct A;\n");
    tmp.file("src/deep/mod.rs", "mod x;\n");
    tmp.file("Cargo.toml", "[package]\nname = \"a\"\n");
    let d = DiskSource::new(tmp.0.clone());
    let root = d.list("").unwrap();
    let names: Vec<(&str, EntryKind)> = root.iter().map(|e| (e.name.as_str(), e.kind)).collect();
    assert_eq!(names, [("Cargo.toml", EntryKind::File), ("src", EntryKind::Dir)]);
    assert_eq!(d.read("src/lib.rs", 100).unwrap(), b"pub struct A;\n");
    assert_eq!(d.read("src/lib.rs", 3), Err(ReadError::TooLarge(14)));
    assert_eq!(d.read("src/none.rs", 100), Err(ReadError::NotFound));
    let meta = d.stat("src/lib.rs").unwrap();
    assert_eq!(meta.size, 14);
    assert!(meta.mtime_ms > 1_000_000_000_000, "{meta:?}");
    assert_eq!(d.list("src").unwrap().len(), 2);
    assert!(d.list("missing").is_err());
}

#[cfg(unix)]
#[test]
fn a_disk_source_does_not_follow_a_symlink_and_never_reads_a_folder_as_a_file() {
    let tmp = Tmp::new("link");
    tmp.file("real/a.rs", "x");
    std::os::unix::fs::symlink(tmp.0.join("real"), tmp.0.join("loop")).unwrap();
    let d = DiskSource::new(tmp.0.clone());
    let root = d.list("").unwrap();
    let kinds: Vec<(&str, EntryKind)> = root.iter().map(|e| (e.name.as_str(), e.kind)).collect();
    assert_eq!(kinds, [("loop", EntryKind::Other), ("real", EntryKind::Dir)]);
    assert!(d.read("real", 10).is_err());
}

