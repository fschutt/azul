//! Where the files come from: what a file is by its name, which are test files, which are not
//! worth reading, the walk's exclusions, the memory source the tests use and the disk source the
//! app uses. No window, no azul.

use super::*;

fn mem(files: &[(&str, &str)]) -> MemSource {
    let mut m = MemSource::new();
    for (path, text) in files {
        m.put(path, text.as_bytes().to_vec());
    }
    m
}

/// A folder of this test, removed when it goes out of scope.
struct Tmp(std::path::PathBuf);

impl Tmp {
    fn new(label: &str) -> Self {
        let dir = std::env::temp_dir().join(format!("azreview-symbols-{label}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        Self(dir)
    }

    fn file(&self, rel: &str, text: &str) {
        let path = self.0.join(rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }
}

impl Drop for Tmp {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

