#[test]
fn a_file_with_a_nul_byte_is_binary_and_one_with_bad_utf8_and_no_nul_is_not() {
    assert_eq!(inspect(b"fn main() {}\0\0\0"), Some(SkipReason::Binary));
    assert_eq!(inspect(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A, 0, 0, 0, 0x0D]), Some(SkipReason::Binary));
    assert_eq!(inspect(b"let s = \"caf\xE9\";\n"), None);
    assert_eq!(inspect(b""), None);
}

#[test]
fn a_file_that_says_at_its_top_it_is_generated_is_skipped_and_one_that_says_so_later_is_not() {
    for top in [
        "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
        "/* @generated */\nint a;\n",
        "# This file is automatically generated by a tool\nx = 1\n",
        "// DO NOT EDIT: made by the build\nfn a() {}\n",
        "//! Auto-generated bindings\n",
    ] {
        assert_eq!(inspect(top.as_bytes()), Some(SkipReason::Generated), "{top}");
    }
    let mut late = String::from("fn a() {}\n").repeat(200);
    late.push_str("// this part is generated by hand, do not edit\n");
    assert_eq!(inspect(late.as_bytes()), None);
}

#[test]
fn a_script_that_writes_or_describes_a_generated_file_is_not_itself_generated() {
    // The marker is read where a generated file says it: on a comment line. A generator has the words in a
    // string it writes, in the prose of its docstring, in a message it prints.
    for script in [
        "\"\"\"Writes the table.\n\nThe generated file holds the lowering of every type.\n\"\"\"\n\ndef main():\n    pass\n",
        "fn header() -> &'static str {\n    \"// @generated by the tool, do not edit\"\n}\n",
        "print('# DO NOT EDIT: generated by gen.py')\n",
        "import os\nHEADER = \"\"\"/* Code generated by gen.py. DO NOT EDIT. */\n\"\"\"\n",
        "int main() { return 0; } // a file generated by hand\n",
        "    s.push_str(\"# WARNING: autogenerated by the codegen -- DO NOT EDIT MANUALLY.\\n\");\n",
    ] {
        assert_eq!(inspect(script.as_bytes()), None, "{script}");
    }
    // The comment openers of the languages, a byte order mark in front, indentation, and a docstring's first line.
    for top in [
        "\u{feff}// Code generated by protoc. DO NOT EDIT.\n",
        "   # This file is autogenerated\n",
        "-- generated by a tool\n",
        "<!-- auto-generated -->\n",
        " * @generated\n",
        "\"\"\"Auto-generated by the build.\"\"\"\n",
        "#!/bin/sh\n# generated by configure\n",
    ] {
        assert_eq!(inspect(top.as_bytes()), Some(SkipReason::Generated), "{top}");
    }
}

#[test]
fn a_weak_word_makes_a_file_generated_only_at_its_very_top_and_never_in_a_doc_comment() {
    // "generated by" and "generated file" are also what the docs of a code generator say about the file it writes.
    for hand_written in [
        "//! Layers of the generated file, top to bottom:\nfn a() {}\n",
        "/// shader source into the generated file.\nfn a() {}\n",
        "//! The table is embedded (generated by `tool all`)\n",
        "fn a() {}\nfn b() {}\nfn c() {}\n// the generated file tree\nfn d() {}\n",
        "#!/usr/bin/env python3\n\"\"\"Docs.\"\"\"\n\n# Local: resolve every href against the generated file tree.\n",
    ] {
        assert_eq!(inspect(hand_written.as_bytes()), None, "{hand_written}");
    }
    for generated in [
        "// My App - generated by AzBuilder (azul-css codegen, Go).\npackage main\n",
        "# My App - generated by AzBuilder\nimport x\n",
        "#!/bin/sh\n# generated by configure\n",
        "/* generated file */\n",
        "//! Auto-generated bindings\n",
    ] {
        assert_eq!(inspect(generated.as_bytes()), Some(SkipReason::Generated), "{generated}");
    }
}

